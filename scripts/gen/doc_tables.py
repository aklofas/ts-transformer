#!/usr/bin/env python3
"""Write (or check) the documentation tables that restate a machine source.

Each generated region sits between `<!-- BEGIN GENERATED by
scripts/gen/doc-tables.sh (NAME); do not edit -->` and `<!-- END GENERATED by
scripts/gen/doc-tables.sh (NAME) -->` in its document; everything outside the
markers is hand-written and never touched.

  targets      docs/reference/compatibility.md   ci.yml `build` + test matrices
  sanitizers   docs/reference/compatibility.md   sanitizers.yml jobs + cron
  fuzz         docs/reference/compatibility.md   tests/coverage/fuzz-targets.toml
  features     docs/languages/rust.md            `cargo metadata` [features]
  manifests    tests/coverage/README.md          tests/coverage/*.toml

Usage:  doc_tables.py [--root DIR] [--write | --check]

`cargo metadata` runs in ROOT unless DOC_TABLES_METADATA names a saved JSON
file. Stdlib only; the YAML files are read with a line scanner.
"""
import argparse
import glob
import json
import os
import re
import subprocess
import sys

try:
    import tomllib
except ImportError:  # Python < 3.11
    print("doc-tables: doc_tables.py needs Python >= 3.11 (tomllib)", file=sys.stderr)
    sys.exit(1)

# (crate dir, feature) rows of the feature table, in display order.
FEATURE_ROWS = [
    ("srt-sys", "mbedtls"),
    ("tst-srt", "mbedtls"),
    ("tst-core", "std"),
    ("tst-core", "file"),
    ("tst-core", "tls"),
    ("tst-webrtc", "tls"),
]

# The Effect column: what a feature does cannot be derived from Cargo.toml.
FEATURE_NOTES = {
    "srt-sys/mbedtls": "Builds encryption support using mbedTLS. Set a passphrase on both peers to encrypt a connection.",
    "tst-srt/mbedtls": "Propagates to `srt-sys/mbedtls`.",
    "tst-core/std": "Standard library: file I/O, net helpers, JSON/TOML. Off = `#![no_std]` + `alloc` (see [embedded](/docs/languages/embedded.md)).",
    "tst-core/file": "File I/O helpers. `file` and `std` imply each other, so they switch on and off together.",
    "tst-core/tls": "PEM loading for the rustls-based transports (`net::tls`). The transport crates' `tls` features turn it on.",
    "tst-webrtc/tls": "HTTPS (`wheps://`) for the WHEP signalling endpoint. Turns on `tst-core/tls`.",
}

# (document, block name) in the order they are written.
BLOCKS = [
    ("docs/reference/compatibility.md", "targets"),
    ("docs/reference/compatibility.md", "sanitizers"),
    ("docs/reference/compatibility.md", "fuzz"),
    ("docs/languages/rust.md", "features"),
    ("tests/coverage/README.md", "manifests"),
]


def die(msg):
    print("doc-tables: " + msg, file=sys.stderr)
    sys.exit(1)


# ---- sources ---------------------------------------------------------------

def parse_build_legs(ci_text):
    """The legs of the `build` job's `include:` list.

    Every `- ` line under `include:` starts a leg and `name`/`runner`/`phase`
    are read from any key position; a leg without a name or a runner is an
    error, so a reshaped matrix can never be dropped or half-read silently.
    """
    legs, in_build, in_include, cur = [], False, False, None
    for line in ci_text.splitlines():
        if re.match(r"^  [A-Za-z0-9_-]+:\s*$", line):
            in_build = line.strip() == "build:"
            in_include = False
            continue
        if not in_build:
            continue
        if re.match(r"^\s+include:\s*$", line):
            in_include = True
            continue
        if not in_include:
            continue
        if re.match(r"^    \S", line):
            in_include = False  # `steps:` or any key after the matrix
            continue
        if re.match(r"^\s+-(\s|$)", line):
            cur = {}
            legs.append(cur)
            line = re.sub(r"^(\s+)-", r"\1 ", line)
        m = re.match(r"^\s+(name|runner|phase|platform):\s*(\S+)\s*$", line)
        if m and cur is not None:
            cur[m.group(1)] = m.group(2)
    for i, leg in enumerate(legs):
        label = leg.get("name") or "#%d" % (i + 1)
        for key in ("name", "runner"):
            if not leg.get(key):
                die("ci.yml build matrix leg %s has no `%s`" % (label, key))
        leg.setdefault("phase", "")
        leg.setdefault("platform", leg["name"])
    return legs


TEST_JOBS = ("test-linux", "test-platforms", "test-main-extra")


def parse_test_legs(ci_text):
    """The include entries of the three test jobs, with each job's shard count.

    Matrix axis lines (`shard: [1, 2]`, `name: [...]`, `pass: [...]`) precede
    `include:` and are not entries; only the `- ` lines after `include:` start
    one. `shards` is the length of the job's `shard:` axis. An entry without a
    name, runner or pass, or a job without a shard axis, is an error.
    """
    legs, job, in_include, cur, shards = [], None, False, None, {}
    for line in ci_text.splitlines():
        m = re.match(r"^  ([A-Za-z0-9_-]+):\s*$", line)
        if m:
            job = m.group(1) if m.group(1) in TEST_JOBS else None
            in_include = False
            continue
        if job is None:
            continue
        m = re.match(r"^\s+shard:\s*\[([^\]]*)\]", line)
        if m and not in_include:
            shards[job] = len([x for x in m.group(1).split(",") if x.strip()])
            continue
        if re.match(r"^\s+include:\s*$", line):
            in_include = True
            continue
        if not in_include:
            continue
        if re.match(r"^    \S", line):
            in_include = False
            continue
        if re.match(r"^\s+-(\s|$)", line):
            cur = {"job": job}
            legs.append(cur)
            line = re.sub(r"^(\s+)-", r"\1 ", line)
        m = re.match(r"^\s+(name|runner|pass):\s*(\S+)\s*$", line)
        if m and cur is not None:
            cur[m.group(1)] = m.group(2)
    for i, leg in enumerate(legs):
        label = leg.get("name") or "#%d" % (i + 1)
        for key in ("name", "runner", "pass"):
            if not leg.get(key):
                die("ci.yml %s matrix leg %s has no `%s`" % (leg["job"], label, key))
        if leg["job"] not in shards:
            die("ci.yml job %s has no `shard:` axis" % leg["job"])
        leg["shards"] = shards[leg["job"]]
    return legs


def parse_sanitizers(text):
    jobs, in_jobs, cron = [], False, None
    for line in text.splitlines():
        m = re.match(r"^\s*-\s*cron:\s*'([^']*)'", line)
        if m and cron is None:
            cron = m.group(1)
        if re.match(r"^jobs:\s*$", line):
            in_jobs = True
            continue
        if in_jobs:
            m = re.match(r"^  ([A-Za-z0-9_-]+):\s*$", line)
            if m:
                jobs.append(m.group(1))
    return jobs, cron


def fuzz_counts(toml_text):
    counts = {}
    for t in tomllib.loads(toml_text).get("target", []):
        counts[t["crate"]] = counts.get(t["crate"], 0) + 1
    return sorted(counts.items())


def load_metadata(root):
    saved = os.environ.get("DOC_TABLES_METADATA")
    if saved:
        with open(saved, encoding="utf-8") as f:
            return json.load(f)
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--no-deps", "--offline"],
        cwd=root, check=True, capture_output=True, text=True,
    ).stdout
    return json.loads(out)


# ---- renderers --------------------------------------------------------------

def render_targets(build_legs, test_legs):
    platforms = []  # one row per platform, in build order; the first leg names the runner
    for leg in build_legs:
        for p in platforms:
            if p["name"] == leg["platform"]:
                p["jobs"].append(leg["name"])
                break
        else:
            platforms.append({"name": leg["platform"], "runner": leg["runner"], "jobs": [leg["name"]]})

    def cell(platform, jobs):
        passes = ", ".join(
            "`%s` ×%d" % (t["pass"], t["shards"])
            for t in test_legs if t["name"] == platform and t["job"] in jobs)
        return passes or "—"

    rows = [
        "| Target | Runner | Build jobs | Tests on a PR | Tests on main only |",
        "|---|---|---|---|---|",
    ]
    for p in platforms:
        built = ", ".join("`build (%s)`" % n for n in p["jobs"])
        rows.append("| `%s` | `%s` | %s | %s | %s |" % (
            p["name"], p["runner"], built,
            cell(p["name"], ("test-linux", "test-platforms")),
            cell(p["name"], ("test-main-extra",))))
    return "\n".join(rows)


def render_sanitizers(jobs, cron):
    return "Schedule: `%s` (UTC). %d jobs: %s." % (
        cron, len(jobs), ", ".join("`%s`" % j for j in jobs))


def render_fuzz(counts):
    total = sum(n for _, n in counts)
    parts = ", ".join("%d in `%s`" % (n, c) for c, n in counts)
    return "%d cargo-fuzz harnesses live in-tree (%s)." % (total, parts)


def _default_closure(features):
    seen, todo = set(), list(features.get("default", []))
    while todo:
        f = todo.pop()
        if f in seen or f not in features:
            continue
        seen.add(f)
        todo.extend(features[f])
    return seen


def render_features(meta, rows, notes):
    by_dir = {}
    for p in meta["packages"]:
        by_dir[os.path.basename(os.path.dirname(p["manifest_path"]))] = p
    out = ["| Crate | Feature | Default | Effect |", "|---|---|---|---|"]
    for crate, feat in rows:
        pkg = by_dir.get(crate)
        if pkg is None:
            die("crate directory %r is not a workspace member" % crate)
        if feat not in pkg["features"]:
            die("%s has no feature %r" % (crate, feat))
        note = notes.get("%s/%s" % (crate, feat))
        if note is None:
            die("no Effect note for %s/%s" % (crate, feat))
        label = "`%s`" % crate
        if pkg["name"] != crate:
            label += " (published as `%s`)" % pkg["name"]
        on = "on" if feat in _default_closure(pkg["features"]) else "off"
        out.append("| %s | `%s` | %s | %s |" % (label, feat, on, note))
    return "\n".join(out)


def render_manifests(names):
    names = sorted(names)
    return "%d manifests live here: %s." % (
        len(names), ", ".join("`%s`" % n for n in names))


# ---- blocks -------------------------------------------------------------------

def replace_block(text, name, content):
    begin = "<!-- BEGIN GENERATED by scripts/gen/doc-tables.sh (%s); do not edit -->" % name
    end = "<!-- END GENERATED by scripts/gen/doc-tables.sh (%s) -->" % name
    b, e = text.find(begin), text.find(end)
    if b < 0 or e < b:
        die("markers for block %r not found" % name)
    return text[: b + len(begin)] + "\n" + content + "\n" + text[e:]


def render_all(root):
    def read(rel):
        with open(os.path.join(root, rel), encoding="utf-8") as f:
            return f.read()

    jobs, cron = parse_sanitizers(read(".github/workflows/sanitizers.yml"))
    ci = read(".github/workflows/ci.yml")
    legs = parse_build_legs(ci)
    if not legs or not jobs or not cron:
        die("could not read the build matrix or the sanitizer workflow")
    manifests = [os.path.basename(p) for p in glob.glob(os.path.join(root, "tests/coverage/*.toml"))]
    return {
        "targets": render_targets(legs, parse_test_legs(ci)),
        "sanitizers": render_sanitizers(jobs, cron),
        "fuzz": render_fuzz(fuzz_counts(read("tests/coverage/fuzz-targets.toml"))),
        "features": render_features(load_metadata(root), FEATURE_ROWS, FEATURE_NOTES),
        "manifests": render_manifests(manifests),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = ap.parse_args()
    root = os.path.abspath(args.root)
    rendered = render_all(root)

    docs = {}
    for rel, name in BLOCKS:
        path = os.path.join(root, rel)
        if rel not in docs:
            with open(path, encoding="utf-8") as f:
                docs[rel] = f.read()
        new = replace_block(docs[rel], name, rendered[name])
        if args.check and new != docs[rel]:
            print("doc-tables: %s block %r is stale; run scripts/gen/doc-tables.sh" % (rel, name), file=sys.stderr)
            sys.exit(1)
        docs[rel] = new
    if args.check:
        print("doc-tables: OK (%d blocks)" % len(BLOCKS))
        return
    for rel, text in docs.items():
        with open(os.path.join(root, rel), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print("doc-tables: wrote %d blocks in %d files" % (len(BLOCKS), len(docs)))


if __name__ == "__main__":
    main()
