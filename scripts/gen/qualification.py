#!/usr/bin/env python3
"""The qualification record: one JSON file per qualified tree, rendered into the evidence page.

  collect   --artifacts DIR --out FILE [--root DIR]   read a release-qualify run's artefacts
  render    --json FILE (--write | --check) [--root DIR]   the generated block in
            docs/project/validation-evidence.md
  checksums --dir DIR                                  write DIR/SHA256SUMS
  archives  [--root DIR]                               validate tests/coverage/evidence-archives.toml

Artefact directory read by `collect` (a missing file is a missing leg, never a pass):
  context.json                         label, source{sha,ref,dirty,submodules}, toolchain, host
  legs.json                            {leg: {conclusion, run_url}} for interop, jvm-jar,
                                       python-wheels, c-abi, fuzz, semver-checks and a
                                       "sanitizers" run_url
  ci.json                              {conclusion, run_url} of the ci workflow on the sha
  interop-evidence/{results,inventory}.json
  sanitizer-<job>/sanitizer-<job>.json (or sanitizer-<job>.json) {job, conclusion}
  fuzz.json, abi.json, semver-checks.json

A leg is GO only when its conclusion is exactly `success`. Stdlib only.
"""
import argparse
import hashlib
import json
import os
import re
import sys

try:
    import tomllib
except ImportError:  # Python < 3.11
    print("qualification: needs Python >= 3.11 (tomllib)", file=sys.stderr)
    sys.exit(1)

PAGE = "docs/project/validation-evidence.md"
ANCHOR = "## Evidence for the 0.8.0 tree"
BEGIN = "<!-- BEGIN GENERATED by scripts/gen/qualification.sh (evidence); do not edit -->"
END = "<!-- END GENERATED by scripts/gen/qualification.sh (evidence) -->"

EMPTY_BLOCK = (
    BEGIN + "\n"
    "## Evidence for the latest qualified tree\n\n"
    "No release qualification is recorded yet. The `release-qualify` workflow produces one "
    "record per tagged commit; committing it as `docs/project/qualification.json` fills "
    "this section.\n"
    + END
)

SANITIZER_JOBS = ["asan", "asan-native", "tsan", "tsan-native"]
REQUIRED_LEGS = (["interop"] + ["sanitizers/" + j for j in SANITIZER_JOBS]
                 + ["fuzz", "jvm-jar", "python-wheels", "c-abi", "ci (on this sha)"])
KINDS = ("soak", "stress", "corpus")
MAINTAINER_LOCAL = [
    "real-capture corpus cross-check (cargo test -p tst-core --test mpegts mux_local)",
    "long fuzz runs (10 min per target)",
    "bench regression",
    "one-hour synthetic soak",
]
PEER_KEYS = ("ffmpeg", "tsp", "gst-launch-1.0", "vlc", "mpv")


def die(msg, rc=2):
    print("qualification: " + msg, file=sys.stderr)
    sys.exit(rc)


def read_json(path):
    try:
        with open(path) as f:
            return json.load(f)
    except FileNotFoundError:
        return None
    except ValueError as e:
        die("%s is not valid JSON: %s" % (path, e))


# ---- archives --------------------------------------------------------------

def parse_archives(text):
    return tomllib.loads(text).get("archive", [])


def validate_archives(rows):
    problems, seen = [], set()
    for r in rows:
        i = r.get("id", "?")
        if i in seen:
            problems.append("duplicate archive id " + i)
        seen.add(i)
        if r.get("kind") not in KINDS:
            problems.append("%s: unknown kind %r" % (i, r.get("kind")))
        if not re.fullmatch(r"[0-9a-f]{40}", str(r.get("tree", ""))):
            problems.append("%s: tree is not a 40-hex commit" % i)
        if not isinstance(r.get("overall_pass"), bool):
            problems.append("%s: overall_pass must be true or false" % i)
        if not r.get("note") or not re.fullmatch(r"\d{4}-\d\d-\d\d", str(r.get("date", ""))):
            problems.append("%s: note and a YYYY-MM-DD date are required" % i)
    return problems


def load_archives(root):
    path = os.path.join(root, "tests/coverage/evidence-archives.toml")
    with open(path) as f:
        rows = parse_archives(f.read())
    probs = validate_archives(rows)
    if probs:
        die("evidence-archives.toml: " + "; ".join(probs), 1)
    return [{k: r[k] for k in ("id", "kind", "tree", "overall_pass", "note", "date")} for r in rows]


# ---- collect ---------------------------------------------------------------

def _strip(describe, *prefixes):
    for p in prefixes:
        if describe.startswith(p):
            return describe[len(p):]
    return describe


def _find_sanitizer(art, job):
    name = "sanitizer-" + job
    for p in (os.path.join(art, name, name + ".json"), os.path.join(art, name + ".json")):
        d = read_json(p)
        if d is not None:
            return d
    return None


def _interop(art, legs):
    results = read_json(os.path.join(art, "interop-evidence", "results.json"))
    inv = read_json(os.path.join(art, "interop-evidence", "inventory.json")) or {}
    if results is None:
        return None, {}
    s, i = results.get("summary", {}), results.get("inventory", {})
    shape = i.get("shape", "unknown")
    if shape == "full":
        shape = "full-%d" % i.get("declared_cells", s.get("total", 0))
    rec = {
        "shape": shape, "total": s.get("total", 0), "pass": s.get("pass", 0),
        "fail": s.get("fail", 0), "expected_unsupported": s.get("expected_unsupported", 0),
        "skipped": s.get("skipped_tool_missing", 0),
        "stale": len(s.get("stale_expectations", [])),
        "expected_full_cells": i.get("expected_full_cells", 0),
        "au_sizes": results.get("meta", {}).get("au_sizes", "unrecorded"),
    }
    return rec, dict(inv.get("tools", {}))


def verdict(legs, interop, fuzz):
    reasons = []
    for l in legs:
        if l["required"] and l["conclusion"] != "success":
            reasons.append("%s: %s" % (l["name"], l["conclusion"]))
    if interop is None:
        reasons.append("interop: no census recorded")
    else:
        if not interop["shape"].startswith("full"):
            reasons.append("interop: shape is %s, not a full census" % interop["shape"])
        if interop["total"] != interop["expected_full_cells"]:
            reasons.append("interop: total %d differs from the declared full census %d"
                           % (interop["total"], interop["expected_full_cells"]))
        for k in ("fail", "skipped", "stale"):
            if interop[k]:
                reasons.append("interop: %s is %d, not 0" % (k, interop[k]))
    if fuzz is None:
        reasons.append("fuzz: no result recorded")
    else:
        if fuzz["crashes"]:
            reasons.append("fuzz: %d crash(es)" % fuzz["crashes"])
        if fuzz["targets_run"] != fuzz["targets_declared"]:
            reasons.append("fuzz: ran %d of %d declared targets"
                           % (fuzz["targets_run"], fuzz["targets_declared"]))
    return ("GO" if not reasons else "NO-GO"), reasons


def collect(art, root):
    ctx = read_json(os.path.join(art, "context.json"))
    if ctx is None:
        die("context.json is missing from " + art)
    legs_in = read_json(os.path.join(art, "legs.json")) or {}

    def entry(name):
        e = legs_in.get(name) or {}
        return e.get("conclusion"), e.get("run_url", "")

    interop, peers_all = _interop(art, legs_in)
    fuzz_in = read_json(os.path.join(art, "fuzz.json"))
    declared = 0
    with open(os.path.join(root, "tests/coverage/fuzz-targets.toml")) as f:
        declared = len(tomllib.loads(f.read()).get("target", []))
    fuzz = None
    if fuzz_in is not None:
        fuzz = {"targets_declared": declared, "targets_run": fuzz_in.get("targets_run", 0),
                "seconds_per_target": fuzz_in.get("seconds_per_target", 0),
                "crashes": fuzz_in.get("crashes", 0)}
    abi_in = read_json(os.path.join(art, "abi.json"))
    ci_in = read_json(os.path.join(art, "ci.json"))

    legs = []

    def add(name, conclusion, url, required=True):
        legs.append({"name": name, "required": required,
                     "conclusion": conclusion or "missing", "run_url": url or ""})

    c, u = entry("interop")
    add("interop", c if interop is not None else "missing", u)
    san_url = (legs_in.get("sanitizers") or {}).get("run_url", "")
    for j in SANITIZER_JOBS:
        s = _find_sanitizer(art, j)
        add("sanitizers/" + j, (s or {}).get("conclusion"), san_url)
    c, u = entry("fuzz")
    add("fuzz", c if c else (None if fuzz is None else ("success" if not fuzz["crashes"] else "failure")), u)
    for n in ("jvm-jar", "python-wheels"):
        c, u = entry(n)
        add(n, c, u)
    c, u = entry("c-abi")
    if c is None and abi_in is not None:
        c = "success" if abi_in.get("verdict") == "compatible" else "failure"
    add("c-abi", c, u)
    add("ci (on this sha)", (ci_in or {}).get("conclusion"), (ci_in or {}).get("run_url"))
    c, u = entry("semver-checks")
    add("semver-checks", c, u, required=False)

    subs = ctx.get("source", {}).get("submodules", {})

    def native(path, *prefixes):
        return _strip(subs.get(path, {}).get("describe", "unknown"), *prefixes)

    natives = {"libsrt": native("crates/srt-sys/vendor/srt", "v"),
               "librist": native("crates/rist-sys/vendor/librist", "v"),
               "mbedtls": native("crates/mbedtls-src/vendor/mbedtls", "mbedtls-", "v")}
    sc = []
    for r in read_json(os.path.join(art, "semver-checks.json")) or []:
        sc.append({"crate": r["crate"], "breaking": r.get("failed_checks", 0),
                   "exit": r["exit"], "analysed": r.get("analysed", False)})
    v, reasons = verdict(legs, interop, fuzz)
    return {
        "schema_version": 0,
        "label": ctx.get("label", "unlabelled"),
        "source": ctx.get("source", {}),
        "toolchain": ctx.get("toolchain", {}),
        "natives": natives,
        "host": ctx.get("host", {}),
        "peers": {k: peers_all[k] for k in peers_all} if peers_all else {},
        "legs": legs,
        "interop": interop,
        "fuzz": fuzz,
        "abi": abi_in,
        "semver_checks": sc,
        "archives": load_archives(root),
        "maintainer_local": list(MAINTAINER_LOCAL),
        "verdict": v,
        "verdict_reasons": reasons,
    }


# ---- render ----------------------------------------------------------------

def _leg_line(l):
    s = "- `%s`: %s" % (l["name"], l["conclusion"])
    if l["run_url"]:
        s += " ([run](%s))" % l["run_url"]
    if not l["required"]:
        s += ", informational"
    return s + "."


def render_block(rec):
    src = rec["source"]
    out = ["## Evidence for the %s tree" % rec["label"], ""]
    subs = src.get("submodules", {})
    nat = rec["natives"]
    out.append(
        "Qualified commit `%s` (`%s`, %s tree). Bundled natives: libsrt %s, librist %s, "
        "mbedTLS %s. Toolchain: %s; public API pinned to %s; cbindgen %s. Runner: %s %s, "
        "kernel %s." % (
            src.get("sha", "?")[:12], src.get("ref", "?"),
            "a modified" if src.get("dirty") else "a clean",
            nat["libsrt"], nat["librist"], nat["mbedtls"],
            rec["toolchain"].get("rust", "unrecorded"),
            rec["toolchain"].get("nightly_public_api", "unrecorded"),
            rec["toolchain"].get("cbindgen", "unrecorded"),
            rec["host"].get("runner", "?"), rec["host"].get("arch", "?"),
            rec["host"].get("kernel", "?")))
    out.append("")
    if rec["verdict"] == "GO":
        out.append("Verdict: **GO**. Every required leg succeeded on this commit.")
    else:
        out.append("Verdict: **NO-GO**.")
        out.append("")
        out.extend("- %s" % r for r in rec["verdict_reasons"])
    out += ["", "Test legs on this commit:", ""]
    out.extend(_leg_line(l) for l in rec["legs"])
    out.append("")
    i = rec["interop"]
    if i is None:
        out.append("The interop census is not recorded.")
    else:
        out.append(
            "The interop census (%s) reads %d / %d / %d / %d / %d: total, pass, fail, "
            "expected-unsupported, skipped. Stale expectations: %d. The declared full "
            "census is %d cells, at %s access-unit sizes." % (
                i["shape"], i["total"], i["pass"], i["fail"], i["expected_unsupported"],
                i["skipped"], i["stale"], i["expected_full_cells"], i["au_sizes"]))
    if rec["peers"]:
        out.append("")
        out.append("Peer tools: " + ", ".join(
            "%s %s" % (k, rec["peers"][k]) for k in sorted(rec["peers"])) + ".")
    f = rec["fuzz"]
    out.append("")
    if f is None:
        out.append("The fuzz result is not recorded.")
    else:
        out.append("Fuzz: %d of %d declared targets ran for %d s each with %d crash(es)." % (
            f["targets_run"], f["targets_declared"], f["seconds_per_target"], f["crashes"]))
    a = rec["abi"]
    out.append("")
    if a is None:
        out.append("The C ABI comparison is not recorded.")
    else:
        out.append(
            "C ABI %s.%s with %s exported symbols, compared with %s (%s): abidiff exit %s, %s." % (
                a.get("major"), a.get("minor"), a.get("symbols"), a.get("previous_tag"),
                a.get("previous_source"), a.get("abidiff_exit"), a.get("verdict")))
    if rec["semver_checks"]:
        out.append("")
        out.append("cargo-semver-checks, informational: " + "; ".join(
            "%s %s" % (s["crate"], ("%d breaking" % s["breaking"]) if s["analysed"] else "not analysed")
            for s in rec["semver_checks"]) + ".")
    out += ["", "Cited soak, stress and corpus archives, with the verdicts they recorded:", ""]
    for r in rec["archives"]:
        out.append("- `%s` (%s, %s, tree `%s`): `overall_pass=%s`. %s" % (
            r["id"], r["kind"], r["date"], r["tree"][:12],
            "true" if r["overall_pass"] else "false", r["note"]))
    out += ["", "Checks that stay with the maintainer and are not part of this record:", ""]
    out.extend("- " + m for m in rec["maintainer_local"])
    return "\n".join(out) + "\n"


def wrapped(rec):
    if rec is None:
        return EMPTY_BLOCK
    return BEGIN + "\n" + render_block(rec) + END


def replace_block(text, block):
    if BEGIN in text:
        a = text.index(BEGIN)
        b = text.find(END, a)
        if b < 0:
            die("%s has a BEGIN marker without its END marker" % PAGE, 1)
        return text[:a] + block + text[b + len(END):]
    if ANCHOR not in text:
        die("%s has no '%s' heading to insert above" % (PAGE, ANCHOR), 1)
    k = text.index(ANCHOR)
    return text[:k] + block + "\n\n" + text[k:]


def cmd_render(args):
    page = os.path.join(args.root, PAGE)
    with open(page) as f:
        text = f.read()
    rec = read_json(args.json)
    block = wrapped(rec)
    new = replace_block(text, block)
    if args.write:
        if new != text:
            with open(page, "w") as f:
                f.write(new)
        return 0
    if new != text:
        print("qualification: %s is out of date; regenerate with: bash scripts/gen/qualification.sh --write" % PAGE,
              file=sys.stderr)
        return 1
    if rec is None:
        print("qualification: SKIP (no qualification.json is committed; the page says none is recorded)")
    else:
        print("qualification: ok (%s, %s)" % (rec["label"], rec["verdict"]))
    return 0


def write_checksums(d):
    names = sorted(n for n in os.listdir(d)
                   if n != "SHA256SUMS" and os.path.isfile(os.path.join(d, n)))
    lines = []
    for n in names:
        h = hashlib.sha256()
        with open(os.path.join(d, n), "rb") as f:
            for chunk in iter(lambda: f.read(1 << 20), b""):
                h.update(chunk)
        lines.append("%s  %s" % (h.hexdigest(), n))
    with open(os.path.join(d, "SHA256SUMS"), "w") as f:
        f.write("\n".join(lines) + "\n")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    c = sub.add_parser("collect")
    c.add_argument("--artifacts", required=True)
    c.add_argument("--out", required=True)
    c.add_argument("--root", default=".")
    r = sub.add_parser("render")
    r.add_argument("--json", required=True)
    r.add_argument("--root", default=".")
    g = r.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    k = sub.add_parser("checksums")
    k.add_argument("--dir", required=True)
    v = sub.add_parser("archives")
    v.add_argument("--root", default=".")
    args = ap.parse_args(argv)
    if args.cmd == "collect":
        rec = collect(args.artifacts, args.root)
        with open(args.out, "w") as f:
            json.dump(rec, f, indent=2)
            f.write("\n")
        print("qualification: %s (%s)" % (rec["verdict"], "; ".join(rec["verdict_reasons"]) or "all required legs succeeded"))
        return 0
    if args.cmd == "render":
        return cmd_render(args)
    if args.cmd == "checksums":
        write_checksums(args.dir)
        return 0
    load_archives(args.root)
    print("qualification: evidence-archives.toml ok")
    return 0


if __name__ == "__main__":
    sys.exit(main())
