class QualificationError(Exception):
    pass


def die(msg, rc=2):
    print("qualification: " + msg, file=sys.stderr)
    sys.exit(rc)


def read_json(path):
    try:
        with open(path) as f:
            return json.load(f)
    except FileNotFoundError:
        return None
    except ValueError as e:
        die("%s is not valid JSON: %s" % (path, e))


# ---- archives --------------------------------------------------------------

CORPUS_COUNTS = ("files", "identical", "changed_explained", "invariant_failures",
                 "parse_failures", "replay_files", "replay_paths", "replay_failed")


def parse_archives(text):
    return tomllib.loads(text).get("archive", [])


def parse_corpus_expectation(text):
    """The declared size of the release corpus, or None when the file has no [corpus] table."""
    return tomllib.loads(text).get("corpus", {}).get("expected_files")


WAIVER_KEYS = ("verdicts", "reason", "reviewer", "date", "fixed_in")


def _waiver_ok(w):
    if not isinstance(w, dict) or set(w) != set(WAIVER_KEYS):
        return False
    v = w["verdicts"]
    if not isinstance(v, list) or not v or not all(isinstance(x, str) and x for x in v):
        return False
    if not all(isinstance(w[k], str) and w[k] for k in ("reason", "reviewer", "fixed_in")):
        return False
    return bool(re.fullmatch(r"\d{4}-\d\d-\d\d", str(w["date"])))


def disposition(row):
    """`pass`, `waived` or `fail`: the raw verdict, with a waiver beside a failed one."""
    if row.get("overall_pass"):
        return "pass"
    return "waived" if row.get("waiver") else "fail"


DISPOSITION_ORDER = ("pass", "waived", "fail")


def validate_archives(rows):
    problems, seen = [], set()
    for r in rows:
        i = r.get("id", "?")
        if i in seen:
            problems.append("duplicate archive id " + i)
        seen.add(i)
        if r.get("kind") not in KINDS:
            problems.append("%s: unknown kind %r" % (i, r.get("kind")))
        if not re.fullmatch(r"[0-9a-f]{40}", str(r.get("tree", ""))):
            problems.append("%s: tree is not a 40-hex commit" % i)
        if not isinstance(r.get("overall_pass"), bool):
            problems.append("%s: overall_pass must be true or false" % i)
        if not r.get("note") or not re.fullmatch(r"\d{4}-\d\d-\d\d", str(r.get("date", ""))):
            problems.append("%s: note and a YYYY-MM-DD date are required" % i)
        if "waiver" in r:
            if r.get("overall_pass") is not False:
                problems.append("%s: a waiver belongs to a failed row only" % i)
            elif not _waiver_ok(r["waiver"]):
                problems.append("%s: waiver needs verdicts, reason, reviewer, date and fixed_in" % i)
        d = r.get("expected_duration_s")
        if r.get("kind") == "soak":
            if isinstance(d, bool) or not isinstance(d, int) or d <= 0:
                problems.append("%s: a soak row needs expected_duration_s, an integer above 0" % i)
        elif "expected_duration_s" in r:
            problems.append("%s: expected_duration_s belongs to soak rows only" % i)
        if "legs" in r:
            legs = r["legs"]
            if r.get("kind") != "soak":
                problems.append("%s: legs belongs to soak rows only" % i)
            elif (not isinstance(legs, list) or not all(isinstance(l, str) for l in legs)
                  or len(set(legs)) != len(legs) or not set(legs) <= set(RELEASE_SOAK_LEGS)):
                problems.append("%s: legs must be a list of distinct names from %s"
                                % (i, ", ".join(RELEASE_SOAK_LEGS)))
        present = [k for k in CORPUS_COUNTS if k in r]
        if present and r.get("kind") != "corpus":
            problems.append("%s: %s: belongs to corpus rows only" % (i, ", ".join(present)))
        elif present:
            missing = [k for k in CORPUS_COUNTS if k not in r]
            if missing:
                problems.append("%s: corpus counts are all-or-none; missing %s" % (i, ", ".join(missing)))
            for k in present:
                if isinstance(r[k], bool) or not isinstance(r[k], int) or r[k] < 0:
                    problems.append("%s: %s must be an integer, 0 or more" % (i, k))
    return problems


def load_archives(root):
    path = os.path.join(root, "tests/coverage/evidence-archives.toml")
    with open(path) as f:
        text = f.read()
    rows = parse_archives(text)
    expected = parse_corpus_expectation(text)
    probs = validate_archives(rows)
    if isinstance(expected, bool) or not isinstance(expected, int) or expected <= 0:
        probs.append("[corpus] expected_files is required, an integer above 0")
    if probs:
        die("evidence-archives.toml: " + "; ".join(probs), 1)
    out = []
    for r in rows:
        row = {k: r[k] for k in ("id", "kind", "tree", "overall_pass", "note", "date")}
        row["expected_duration_s"] = r.get("expected_duration_s")
        if "legs" in r:
            row["legs"] = r["legs"]
        if "waiver" in r:
            row["waiver"] = r["waiver"]
        row.update({k: r[k] for k in CORPUS_COUNTS if k in r})
        out.append(row)
    return out, expected


# ---- release mode ----------------------------------------------------------

def _diff_names(root, tree, sha):
    cmd = ["git", "-C", root, "diff", "--name-only", "--no-renames", tree, sha]
    try:
        p = subprocess.run(cmd, capture_output=True, text=True)
    except OSError as e:
        raise QualificationError(str(e))
    if p.returncode != 0:
        raise QualificationError(p.stderr.strip() or "git exited %d" % p.returncode)
    return [l for l in p.stdout.splitlines() if l]


def _is_release_document(path):
    if path.startswith(RELEASE_CODE_UNDER_DOCS) and not path.endswith(".md"):
        return False
    return any(path == d or (d.endswith("/") and path.startswith(d)) for d in RELEASE_DOCUMENT_PATHS)


def changed_paths(root, tree, sha):
    """The paths outside RELEASE_DOCUMENT_PATHS that differ between commits `tree` and `sha`."""
    return [l for l in _diff_names(root, tree, sha) if not _is_release_document(l)]


def changed_release_documents(root, tree, sha):
    """The release-document paths that differ between commits `tree` and `sha`, sorted."""
    return sorted(l for l in _diff_names(root, tree, sha) if _is_release_document(l))


def _newest(rows):
    """The row with the latest date; on equal dates the later row in the file."""
    best = None
    for r in rows:
        if best is None or r["date"] >= best["date"]:
            best = r
    return best


def _by_date(rows):
    """Newest first; on equal dates the later row in the file comes first."""
    return [r for _, r in sorted(enumerate(rows), key=lambda p: (p[1]["date"], p[0]), reverse=True)]


def _soak_entry(root, sha, s):
    e = {"id": s["id"], "tree": s["tree"], "date": s["date"],
         "overall_pass": s["overall_pass"], "expected_duration_s": s.get("expected_duration_s"),
         "legs": s.get("legs"), "waiver": s.get("waiver"), "disposition": disposition(s),
         "changed_paths": 0, "git_error": None}
    if s["tree"] != sha:
        try:
            e["changed_paths"] = len(changed_paths(root, s["tree"], sha))
        except QualificationError as err:
            e["changed_paths"] = None
            e["git_error"] = str(err)
    return e


def _pick_soak(root, sha, soaks):
    """The newest 72-hour soak that stands for `sha` (same tree, or no change under
    release documents since); else the newest 72-hour soak; else the newest of any
    duration. Git runs at most once per 72-hour archive."""
    long = [s for s in _by_date(soaks) if s.get("expected_duration_s") == RELEASE_SOAK_S]
    first = None
    for s in long:
        e = _soak_entry(root, sha, s)
        if e["git_error"] is None and e["changed_paths"] == 0:
            return e
        first = first or e
    if first is not None:
        return first
    return _soak_entry(root, sha, _by_date(soaks)[0])


def _check_sha(sha):
    if not re.fullmatch(r"[0-9a-f]{40}", str(sha)):
        raise QualificationError("context.json source.sha is not a 40-hex commit: %r" % (sha,))


def _raw_verdict_reason(kind, entry, allow_waiver):
    """The reason a soak or corpus entry fails the gate on its verdict, or None."""
    if entry["disposition"] == "fail":
        return "%s: archive %s recorded overall_pass=false" % (kind, entry["id"])
    if entry["disposition"] == "waived" and not allow_waiver:
        return ("%s: archive %s is waived (%d verdicts), and a release needs a raw pass"
                % (kind, entry["id"], len(entry["waiver"]["verdicts"])))
    return None


def release_vm(root, sha, archives, release, expected_files, allow_waiver=False):
    """The release gate: the chosen soak archive (see _pick_soak) must stand for
    `sha`, have passed and declared 72 hours, and a passing corpus archive must
    exist for the soaked tree. A waived archive passes only with `allow_waiver`
    (a mid-cycle dispatch); a release needs the harness's own pass. Outside
    release mode the same entries are recorded for information and `reasons`
    stays empty."""
    reasons = []
    soak, corpus = None, None
    soaks = [a for a in archives if a["kind"] == "soak"]
    _check_sha(sha)
    if not soaks:
        reasons.append("soak: no 72-hour soak archive for this tree (%s)" % str(sha)[:12])
    else:
        soak = _pick_soak(root, sha, soaks)
        if soak["git_error"] is not None:
            reasons.append("soak: git could not resolve %s: %s" % (soak["tree"], soak["git_error"]))
        else:
            # The record states what changed between the soaked and the qualified
            # tree, not only that nothing outside the release documents did.
            docs = []
            if soak["tree"] != sha and not soak["changed_paths"]:
                docs = changed_release_documents(root, soak["tree"], sha)
            soak["equivalence"] = {"soaked": soak["tree"], "qualified": sha,
                                   "changed_release_documents": docs}
            if soak["changed_paths"]:
                reasons.append("soak: archive %s is superseded by %d changed path(s) outside the release documents"
                               % (soak["id"], soak["changed_paths"]))
            r = _raw_verdict_reason("soak", soak, allow_waiver)
            if r:
                reasons.append(r)
            # A failed run on the same tree after the chosen one, of any declared
            # duration, is evidence against it; a newer pass never replaces it.
            order = {id(a): i for i, a in enumerate(soaks)}
            chosen = next(a for a in soaks if a["id"] == soak["id"])
            key = lambda a: (a["date"], order[id(a)])
            for a in _by_date(soaks):
                admitted = disposition(a) == "pass" or (allow_waiver and disposition(a) == "waived")
                if a["tree"] == soak["tree"] and not admitted and key(a) > key(chosen):
                    reasons.append("soak: archive %s, a newer run on the same tree, recorded overall_pass=false"
                                   % a["id"])
            if soak["expected_duration_s"] != RELEASE_SOAK_S:
                reasons.append("soak: archive %s declares %s s, not %d"
                               % (soak["id"], soak["expected_duration_s"], RELEASE_SOAK_S))
            elif set(soak.get("legs") or ()) != set(RELEASE_SOAK_LEGS):
                reasons.append("soak: archive %s ran legs %s; the release soak needs %s"
                               % (soak["id"], ", ".join(soak.get("legs") or ()) or "none (undeclared)",
                                  ", ".join(RELEASE_SOAK_LEGS)))
            c = _newest([a for a in archives if a["kind"] == "corpus" and a["tree"] == soak["tree"]])
            if c is None:
                reasons.append("corpus: no corpus archive for the soaked tree %s" % soak["tree"][:12])
            else:
                corpus = {"id": c["id"], "tree": c["tree"], "date": c["date"], "overall_pass": c["overall_pass"],
                          "note": c["note"], "waiver": c.get("waiver"), "disposition": disposition(c)}
                corpus.update({k: c[k] for k in CORPUS_COUNTS if k in c})
                # The release cites the counts; a row without them is hand-typed.
                if any(k not in c for k in CORPUS_COUNTS):
                    reasons.append("corpus: archive %s records no counts; the release gate needs the "
                                   "eight the corpus tool's archive row carries" % c["id"])
                r = _raw_verdict_reason("corpus", corpus, allow_waiver)
                if r:
                    reasons.append(r)
                if all(k in c for k in CORPUS_COUNTS):
                    if c["replay_paths"] != 5:
                        reasons.append("corpus: archive %s replayed %s path(s), not 5"
                                       % (c["id"], c["replay_paths"]))
                    if c["files"] != expected_files:
                        reasons.append("corpus: archive %s swept %d files; the release corpus has %d"
                                       % (c["id"], c["files"], expected_files))
                    if not c["replay_files"] > 0:
                        reasons.append("corpus: archive %s replayed no files" % c["id"])
                    if c["replay_failed"] != 0:
                        reasons.append("corpus: archive %s has %s failed replay(s)"
                                       % (c["id"], c["replay_failed"]))
    # The worse of the two; an entry the gate could not choose counts as a failure.
    worst = max(((e or {}).get("disposition", "fail") for e in (soak, corpus)), key=DISPOSITION_ORDER.index)
    return {"release_mode": bool(release), "soak": soak, "corpus": corpus, "disposition": worst,
            "reasons": reasons if release else []}


# ---- collect ---------------------------------------------------------------

def _strip(describe, *prefixes):
    for p in prefixes:
        if describe.startswith(p):
            return describe[len(p):]
    return describe


def _find_sanitizer(art, job):
    name = "sanitizer-" + job
    for p in (os.path.join(art, name, name + ".json"), os.path.join(art, name + ".json")):
        d = read_json(p)
        if d is not None:
            return d
    return None


CENSUS_COUNTS = ("total", "pass", "fail", "expected_unsupported", "skipped", "stale")


def _arm_census(art):
    """The linux-aarch64 subset census, or None when that job left none. It is
    recorded beside the x86_64 census; the verdict reads only the x86_64 one."""
    c = read_json(os.path.join(art, "interop-census-aarch64.json"))
    if c is None:
        return None
    if (not isinstance(c, dict) or c.get("arch") != "linux-aarch64" or not isinstance(c.get("shape"), str)
            or not all(isinstance(c.get(k), int) and not isinstance(c.get(k), bool) and c[k] >= 0
                       for k in CENSUS_COUNTS)):
        die("interop-census-aarch64.json needs arch linux-aarch64, a shape and the counts %s"
            % ", ".join(CENSUS_COUNTS))
    return {k: c[k] for k in ("arch", "shape") + CENSUS_COUNTS}


def _interop(art):
    results = read_json(os.path.join(art, "interop-evidence", "results.json"))
    inv = read_json(os.path.join(art, "interop-evidence", "inventory.json")) or {}
    arm = _arm_census(art)
    if results is None or not os.path.isfile(os.path.join(art, "interop-evidence", "inventory.json")):
        return None, {}
    s, i = results.get("summary", {}), results.get("inventory", {})
    shape = i.get("shape", "unknown")
    if shape == "full":
        shape = "full-%d" % i.get("declared_cells", s.get("total", 0))
    rec = {
        "shape": shape, "total": s.get("total", 0), "pass": s.get("pass", 0),
        "fail": s.get("fail", 0), "expected_unsupported": s.get("expected_unsupported", 0),
        "skipped": s.get("skipped_tool_missing", 0),
        "stale": len(s.get("stale_expectations", [])),
        "expected_full_cells": i.get("expected_full_cells", 0),
        "au_sizes": results.get("meta", {}).get("au_sizes", "unrecorded"),
    }
    rec["censuses"] = [dict({"arch": "linux-x86_64"}, **{k: rec[k] for k in ("shape",) + CENSUS_COUNTS})]
    if arm is not None:
        rec["censuses"].append(arm)
    return rec, dict(inv.get("tools", {}))


def verdict(legs, interop, fuzz, dirty=False, abi=None, release_vm=None):
    reasons = []
    if abi is not None and abi.get("verdict") != "compatible":
        reasons.append("c-abi: abi.json verdict is %r, not 'compatible'" % abi.get("verdict"))
    if dirty:
        reasons.append("source: the qualified tree had uncommitted changes")
    for l in legs:
        if l["required"] and l["conclusion"] != "success":
            reasons.append("%s: %s" % (l["name"], l["conclusion"]))
    if interop is None:
        reasons.append("interop: no census recorded")
    else:
        if not interop["shape"].startswith("full"):
            reasons.append("interop: shape is %s, not a full census" % interop["shape"])
        if interop["total"] <= 0 or interop["expected_full_cells"] <= 0:
            reasons.append("interop: census undeclared (total %d, declared full census %d)"
                           % (interop["total"], interop["expected_full_cells"]))
        elif interop["total"] != interop["expected_full_cells"]:
            reasons.append("interop: total %d differs from the declared full census %d"
                           % (interop["total"], interop["expected_full_cells"]))
        for k in ("fail", "skipped", "stale"):
            if interop[k]:
                reasons.append("interop: %s is %d, not 0" % (k, interop[k]))
    if fuzz is None:
        reasons.append("fuzz: no result recorded")
    else:
        if fuzz["crashes"]:
            reasons.append("fuzz: %d crash(es)" % fuzz["crashes"])
        if fuzz["targets_run"] != fuzz["targets_declared"]:
            reasons.append("fuzz: ran %d of %d declared targets"
                           % (fuzz["targets_run"], fuzz["targets_declared"]))
    if release_vm is not None and release_vm["release_mode"]:
        reasons.extend(release_vm["reasons"])
    return ("GO" if not reasons else "NO-GO"), reasons


def collect(art, root, release=False, allow_waiver=False, tag=None):
    ctx = read_json(os.path.join(art, "context.json"))
    if ctx is None:
        die("context.json is missing from " + art)
    try:
        _check_sha(ctx.get("source", {}).get("sha", ""))
    except QualificationError as e:
        die(str(e))
    legs_in = read_json(os.path.join(art, "legs.json")) or {}

    def entry(name):
        e = legs_in.get(name) or {}
        return e.get("conclusion"), e.get("run_url", "")

    interop, peers_all = _interop(art)
    fuzz_in = read_json(os.path.join(art, "fuzz.json"))
    declared = 0
    with open(os.path.join(root, "tests/coverage/fuzz-targets.toml")) as f:
        declared = len(tomllib.loads(f.read()).get("target", []))
    fuzz = None
    if fuzz_in is not None:
        fuzz = {"targets_declared": declared, "targets_run": fuzz_in.get("targets_run", 0),
                "seconds_per_target": fuzz_in.get("seconds_per_target", 0),
                "crashes": fuzz_in.get("crashes", 0)}
    abi_in = read_json(os.path.join(art, "abi.json"))
    ci_in = read_json(os.path.join(art, "ci.json"))

    legs = []

    def add(name, conclusion, url, required=True):
        legs.append({"name": name, "required": required,
                     "conclusion": conclusion or "missing", "run_url": url or ""})

    c, u = entry("interop")
    add("interop", c if interop is not None else "missing", u)
    san_url = (legs_in.get("sanitizers") or {}).get("run_url", "")
    for j in SANITIZER_JOBS:
        s = _find_sanitizer(art, j)
        add("sanitizers/" + j, (s or {}).get("conclusion"), san_url)
    c, u = entry("sanitizers")
    add("sanitizers", c, u)
    # The leg record is the only source of the fuzz conclusion: fuzz.json
    # holds the counts the verdict checks, not whether the leg succeeded.
    c, u = entry("fuzz")
    add("fuzz", c, u)
    for n in ("jvm-jar", "python-wheels"):
        c, u = entry(n)
        add(n, c, u)
    c, u = entry("c-abi")
    if abi_in is None:
        c = "missing"
    elif abi_in.get("verdict") != "compatible":
        c = "failure"
    add("c-abi", c, u)
    add("ci (on this sha)", (ci_in or {}).get("conclusion"), (ci_in or {}).get("run_url"))
    c, u = entry("semver-checks")
    add("semver-checks", c, u, required=False)

    subs = ctx.get("source", {}).get("submodules", {})

    def native(path, *prefixes):
        return _strip(subs.get(path, {}).get("describe", "unknown"), *prefixes)

    natives = {"libsrt": native("crates/srt-sys/vendor/srt", "v"),
               "librist": native("crates/rist-sys/vendor/librist", "v"),
               "mbedtls": native("crates/mbedtls-src/vendor/mbedtls", "mbedtls-", "v")}
    sc = []
    for r in read_json(os.path.join(art, "semver-checks.json")) or []:
        sc.append({"crate": r["crate"], "breaking": r.get("failed_checks", 0),
                   "exit": r["exit"], "analysed": r.get("analysed", False)})
    archives, expected_files = load_archives(root)
    try:
        gate = release_vm(root, ctx.get("source", {}).get("sha", ""), archives, release,
                          expected_files, allow_waiver=allow_waiver)
    except QualificationError as e:
        die(str(e))
    v, reasons = verdict(legs, interop, fuzz, bool(ctx.get("source", {}).get("dirty")), abi_in, gate)
    source, label = dict(ctx.get("source", {})), ctx.get("label", "unlabelled")
    if tag:
        source["tag"], label = tag, "tag " + tag
    return {
        "schema_version": 0,
        "label": label,
        "source": source,
        "toolchain": ctx.get("toolchain", {}),
        "natives": natives,
        "host": ctx.get("host", {}),
        "peers": {k: peers_all[k] for k in peers_all} if peers_all else {},
        "legs": legs,
        "interop": interop,
        "fuzz": fuzz,
        "abi": abi_in,
        "semver_checks": sc,
        "archives": archives,
        "release_vm": gate,
        "maintainer_local": list(MAINTAINER_LOCAL),
        "verdict": v,
        "verdict_reasons": reasons,
    }


