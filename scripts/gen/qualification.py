#!/usr/bin/env python3
"""The qualification record: one JSON file per qualified tree, rendered into the evidence page.

  collect   --artifacts DIR --out FILE [--root DIR] [--release] [--allow-waiver] [--tag NAME]
            read a release-qualify run's artefacts; --release also requires the
            72-hour soak and the corpus archives for the qualified tree, each with
            a raw pass unless --allow-waiver admits a maintainer's waiver; --tag names
            the tag a tag push qualified
  render    --json FILE (--write | --check) [--root DIR]   the generated blocks in
            docs/project/validation-evidence.md and docs/project/1.0-exit-criteria.md
  checksums --dir DIR                                  write DIR/SHA256SUMS
  archives  [--root DIR]                               validate tests/coverage/evidence-archives.toml

Artefact directory read by `collect` (a missing file is a missing leg, never a pass):
  context.json                         label, source{sha,ref,dirty,submodules}, toolchain, host
  legs.json                            {leg: {conclusion, run_url}} for interop, jvm-jar,
                                       python-wheels, c-abi, fuzz, semver-checks and
                                       "sanitizers" (the workflow's own conclusion, a
                                       required leg beside its four jobs)
  ci.json                              {conclusion, run_url} of the ci workflow on the sha
  interop-evidence/{results,inventory}.json
  interop-census-aarch64.json          {arch, shape, total, pass, fail, expected_unsupported,
                                       skipped, stale} of the linux-aarch64 subset job, if it ran
  sanitizer-<job>/sanitizer-<job>.json (or sanitizer-<job>.json) {job, conclusion}
  fuzz.json, abi.json, semver-checks.json

A leg is GO only when its conclusion is exactly `success`. An unreadable artefact
makes `collect` exit 2 and a wrongly shaped one fails the run; either way NO record is
written, so the job that runs it must never use `continue-on-error`. Stdlib only.
"""
