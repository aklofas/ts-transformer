def _leg_line(l):
    s = "- `%s`: %s" % (l["name"], l["conclusion"])
    if l["run_url"]:
        s += " ([run](%s))" % l["run_url"]
    if not l["required"]:
        s += ", informational"
    return s + "."


def _verdict_word(e):
    """PASS or FAIL, the raw verdict, with the waiver beside a waived FAIL. A record
    written before waivers existed carries no `waiver` and reads by `overall_pass`."""
    if e["overall_pass"]:
        return "PASS"
    return "FAIL, waived" if e.get("waiver") else "FAIL"


def _release_line(gate):
    """One line naming what the release gate saw. A record written before release
    mode existed has no `release_vm` and reads as not applied."""
    s = (gate or {}).get("soak")
    if s is None:
        soak = "none"
    elif s.get("git_error") is not None:
        soak = "%s (tree %s unresolved)" % (s["id"], s["tree"][:12])
    elif s.get("changed_paths"):
        soak = "%s (superseded by %d code changes)" % (s["id"], s["changed_paths"])
    else:
        legs = (", legs " + ", ".join(s["legs"])) if s.get("legs") else ""
        soak = "%s (tree %s, %s s%s, %s)" % (s["id"], s["tree"][:12], s.get("expected_duration_s"), legs,
                                            _verdict_word(s))
    if not (gate or {}).get("release_mode"):
        return "Release gate: not applied (not a release qualification); newest soak archive for this tree: %s." % soak
    c = gate.get("corpus")
    corpus = "none" if c is None else "%s (%s)" % (c["id"], _verdict_word(c))
    return "Release gate: soak %s, corpus %s." % ("none" if s is None else soak, corpus)


def _release_only(gate):
    """The checks only a release qualification runs; nothing outside release mode."""
    if not (gate or {}).get("release_mode") or not gate.get("corpus"):
        return []
    c = gate["corpus"]
    line = "real-capture corpus: %s" % c["note"]
    if all(k in c for k in CORPUS_COUNTS):
        line += (" (files %(files)d, identical %(identical)d, changed+explained %(changed_explained)d, "
                 "invariant failures %(invariant_failures)d, parse failures %(parse_failures)d; "
                 "replay %(replay_files)d files \u00d7 %(replay_paths)d paths, %(replay_failed)d failed)" % c)
    return ["", "Release-only checks", "", line]


def render_block(rec):
    src = rec["source"]
    out = ["## Evidence for the %s tree" % rec["label"], ""]
    subs = src.get("submodules", {})
    nat = rec["natives"]
    out.append(
        "Qualified commit `%s` (`%s`, %s tree). Bundled natives: libsrt %s, librist %s, "
        "mbedTLS %s. Toolchain: %s; public API pinned to %s; cbindgen %s. Runner: %s %s, "
        "kernel %s." % (
            src.get("sha", "?")[:12], src.get("ref", "?"),
            "a modified" if src.get("dirty") else "a clean",
            nat["libsrt"], nat["librist"], nat["mbedtls"],
            rec["toolchain"].get("rust", "unrecorded"),
            rec["toolchain"].get("nightly_public_api", "unrecorded"),
            rec["toolchain"].get("cbindgen", "unrecorded"),
            rec["host"].get("runner", "?"), rec["host"].get("arch", "?"),
            rec["host"].get("kernel", "?")))
    out.append("")
    if rec["verdict"] == "GO":
        out.append("Verdict: **GO**. Every required leg succeeded on this commit.")
    else:
        out.append("Verdict: **NO-GO**.")
        out.append("")
        out.extend("- %s" % r for r in rec["verdict_reasons"])
    out += ["", _release_line(rec.get("release_vm"))]
    out += _release_only(rec.get("release_vm"))
    out += ["", "Test legs on this commit:", ""]
    out.extend(_leg_line(l) for l in rec["legs"])
    out.append("")
    i = rec["interop"]
    if i is None:
        out.append("The interop census is not recorded.")
    else:
        out.append(
            "The interop census (%s) reads %d / %d / %d / %d / %d: total, pass, fail, "
            "expected-unsupported, skipped. Stale expectations: %d. The declared full "
            "census is %d cells, at %s access-unit sizes." % (
                i["shape"], i["total"], i["pass"], i["fail"], i["expected_unsupported"],
                i["skipped"], i["stale"], i["expected_full_cells"], i["au_sizes"]))
        for c in i.get("censuses", []):
            if c["arch"] == "linux-x86_64":
                continue
            out.append(
                "The %s census (%s) reads %d / %d / %d / %d / %d: total, pass, fail, "
                "expected-unsupported, skipped. Stale expectations: %d." % (
                    c["arch"], c["shape"], c["total"], c["pass"], c["fail"],
                    c["expected_unsupported"], c["skipped"], c["stale"]))
    if rec["peers"]:
        out.append("")
        out.append("Peer tools: " + ", ".join(
            "%s %s" % (k, rec["peers"][k]) for k in sorted(rec["peers"])) + ".")
    f = rec["fuzz"]
    out.append("")
    if f is None:
        out.append("The fuzz result is not recorded.")
    else:
        out.append("Fuzz: %d of %d declared targets ran for %d s each with %d crash(es)." % (
            f["targets_run"], f["targets_declared"], f["seconds_per_target"], f["crashes"]))
    a = rec["abi"]
    out.append("")
    if a is None:
        out.append("The C ABI comparison is not recorded.")
    else:
        out.append(
            "C ABI %s.%s with %s exported symbols, compared with %s (%s): abidiff exit %s, %s." % (
                a.get("major"), a.get("minor"), a.get("symbols"), a.get("previous_tag"),
                a.get("previous_source"), a.get("abidiff_exit"), a.get("verdict")))
    if rec["semver_checks"]:
        out.append("")
        out.append("cargo-semver-checks, informational: " + "; ".join(
            "%s %s" % (s["crate"], ("%d breaking" % s["breaking"]) if s["analysed"] else "not analysed")
            for s in rec["semver_checks"]) + ".")
    out += ["", "Cited soak, stress and corpus archives, with the verdicts they recorded:", ""]
    for r in rec["archives"]:
        declared = (", %d s declared" % r["expected_duration_s"]) if r.get("expected_duration_s") else ""
        w = r.get("waiver")
        if w:
            raw = "overall_pass=false, waived: %d verdict(s) by %s on %s, fixed in %s" % (
                len(w["verdicts"]), w["reviewer"], w["date"], w["fixed_in"])
        else:
            raw = "`overall_pass=%s`" % ("true" if r["overall_pass"] else "false")
        out.append("- `%s` (%s, %s, tree `%s`): %s%s. %s" % (
            r["id"], r["kind"], r["date"], r["tree"][:12], raw, declared, r["note"]))
    out += ["", "Checks that stay with the maintainer and are not part of this record:", ""]
    out.extend("- " + m for m in rec["maintainer_local"])
    return "\n".join(out) + "\n"


def _today(anchor, label, body):
    return '<a id="%s"></a>\n**%s** %s' % (anchor, label, body)


def _soak_desc(s):
    legs = (", legs " + ", ".join(s["legs"])) if s.get("legs") else ""
    return "`%s` (tree `%s`, %s s%s)" % (s["id"], s["tree"][:12], s.get("expected_duration_s"), legs)


def _corpus_desc(c):
    counts = ""
    if all(k in c for k in CORPUS_COUNTS):
        counts = (", %(files)d files, replay %(replay_files)d files \u00d7 %(replay_paths)d paths, "
                  "%(replay_failed)d failed" % c)
    return "`%s` (tree `%s`%s)" % (c["id"], c["tree"][:12], counts)


def _raw_text(row):
    w = row.get("waiver")
    if row["overall_pass"]:
        return "harness verdict PASS"
    if not w:
        return "harness verdict FAIL"
    return "harness verdict FAIL, waived: %d verdict(s) by %s on %s, fixed in %s" % (
        len(w["verdicts"]), w["reviewer"], w["date"], w["fixed_in"])


def _criterion(kind, entry, archives, gate, release):
    """The status sentence of the soak or corpus criterion. The archive table is read
    as it stands now, so a waiver entered after the record was collected shows."""
    row = next((a for a in archives if a["id"] == entry["id"]), entry)
    reasons = [r for r in gate.get("reasons", []) if r.startswith(kind + ":")]
    d = disposition(row)
    if reasons:
        status = "not met: " + reasons[0]
    elif d == "pass":
        status = "met"
    elif d == "waived":
        status = "met by waiver%s; a raw pass is required from %s" % (
            (" (%s)" % release) if release else "", row["waiver"]["fixed_in"])
    else:
        status = "not met: %s: archive %s recorded overall_pass=false" % (kind, row["id"])
    return row, status


def render_exit_criteria(rec, archives, census, release=None):
    """The status paragraphs of the 1.0 exit-criteria page: the soak and corpus
    criteria from the committed record's release gate and the archive table, the
    ARM64 subset from the interop censuses. `release` is the version the record
    qualified, named when a waiver stands in for a raw pass."""
    gate = (rec or {}).get("release_vm") or {}
    soaks = [a for a in archives if a["kind"] == "soak"]
    long = [a for a in _by_date(soaks) if a.get("expected_duration_s") == RELEASE_SOAK_S]
    newest_soak = (long or _by_date(soaks) or [None])[0]
    newest_corpus = _newest([a for a in archives if a["kind"] == "corpus"])
    out = []
    if not gate.get("release_mode"):
        none = "Status: no release qualification is recorded on this tree; the newest %s archive is %s."
        out.append(_today("the-72-hour-soak-today", "The 72-hour soak today.", none % (
            "soak", "none" if newest_soak is None else "%s, %s" % (_soak_desc(newest_soak), _raw_text(newest_soak)))))
        out.append(_today("the-corpus-today", "The corpus today.", none % (
            "corpus", "none" if newest_corpus is None
            else "%s, %s" % (_corpus_desc(newest_corpus), _raw_text(newest_corpus)))))
    else:
        cited = "The committed release qualification (%s) cites %s %s: %s. Status: %s."
        for kind, anchor, label, desc in (("soak", "the-72-hour-soak-today", "The 72-hour soak today.", _soak_desc),
                                          ("corpus", "the-corpus-today", "The corpus today.", _corpus_desc)):
            entry = gate.get(kind)
            if entry is None:
                reasons = [r for r in gate.get("reasons", []) if r.startswith(kind + ":")]
                body = "The committed release qualification (%s) cites no %s archive. Status: not met: %s." % (
                    rec["label"], kind, reasons[0] if reasons else "%s: none recorded" % kind)
            else:
                row, status = _criterion(kind, entry, archives, gate, release)
                body = cited % (rec["label"], kind, desc(dict(entry, **row)), _raw_text(row), status)
            out.append(_today(anchor, label, body))
    arm = next((c for c in census if c.get("arch") == "linux-aarch64"), None)
    if arm is None:
        body = "Status: open: the interop workflow has no linux-aarch64 census."
    else:
        body = "The linux-aarch64 census (%s) reads %d / %d / %d / %d: total, pass, fail, skipped. Status: %s." % (
            arm.get("shape", "unknown"), arm["total"], arm["pass"], arm["fail"], arm["skipped"],
            "met" if arm["fail"] == 0 and arm["total"] > 0
            else "open: the linux-aarch64 census has %d failure(s)" % arm["fail"])
    out.append(_today("the-arm64-subset-today", "The ARM64 subset today.", body))
    return "\n\n".join(out) + "\n"


def exit_wrapped(rec, archives, census, release):
    return EXIT_BEGIN + "\n" + render_exit_criteria(rec, archives, census, release) + EXIT_END


def _release_version(root, rec):
    """The version the committed record qualified: its tag, else the CHANGELOG's
    newest dated section (the record is committed for the release being dated)."""
    tag = ((rec or {}).get("source") or {}).get("tag")
    if tag:
        return tag[1:] if tag.startswith("v") else tag
    try:
        with open(os.path.join(root, "CHANGELOG.md")) as f:
            for line in f:
                m = re.match(r"## \[(\d+\.\d+\.\d+)\] \S+ \d{4}-\d\d-\d\d", line)
                if m:
                    return m.group(1)
    except FileNotFoundError:
        pass
    return None


def _current_archives(root, rec):
    if os.path.isfile(os.path.join(root, "tests/coverage/evidence-archives.toml")):
        return load_archives(root)[0]
    return (rec or {}).get("archives", [])


def wrapped(rec):
    if rec is None:
        return EMPTY_BLOCK
    return BEGIN + "\n" + render_block(rec) + END


def replace_block(text, block, begin=BEGIN, end=END, page=PAGE, anchor=ANCHOR):
    if begin in text:
        a = text.index(begin)
        b = text.find(end, a)
        if b < 0:
            die("%s has a BEGIN marker without its END marker" % page, 1)
        return text[:a] + block + text[b + len(end):]
    if anchor is None:
        die("%s has no generated-block markers" % page, 1)
    if ANCHOR not in text:
        die("%s has no '%s' heading to insert above" % (page, anchor), 1)
    k = text.index(ANCHOR)
    return text[:k] + block + "\n\n" + text[k:]


def cmd_render(args):
    page = os.path.join(args.root, PAGE)
    with open(page) as f:
        text = f.read()
    rec = read_json(args.json)
    if rec is not None and not args.write and (rec["verdict"] != "GO" or rec["label"].startswith("PR #")):
        print("qualification: %s must hold a GO record of a main or tag commit, not %r (%s)"
              % (args.json, rec["label"], rec["verdict"]), file=sys.stderr)
        return 1
    exit_page = os.path.join(args.root, EXIT_PAGE)
    with open(exit_page) as f:
        exit_text = f.read()
    census = ((rec or {}).get("interop") or {}).get("censuses", [])
    pages = [(page, PAGE, text, replace_block(text, wrapped(rec))),
             (exit_page, EXIT_PAGE, exit_text,
              replace_block(exit_text, exit_wrapped(rec, _current_archives(args.root, rec), census,
                                                    _release_version(args.root, rec)),
                            EXIT_BEGIN, EXIT_END, EXIT_PAGE, None))]
    if args.write:
        for path, _, old, new in pages:
            if new != old:
                with open(path, "w") as f:
                    f.write(new)
        return 0
    stale = [name for _, name, old, new in pages if new != old]
    if stale:
        for name in stale:
            print("qualification: %s is out of date; regenerate with: bash scripts/gen/qualification.sh --write"
                  % name, file=sys.stderr)
        return 1
    if rec is None:
        print("qualification: SKIP (no qualification.json is committed; the page says none is recorded)")
    else:
        print("qualification: ok (%s, %s)" % (rec["label"], rec["verdict"]))
    return 0


def write_checksums(d):
    names = sorted(n for n in os.listdir(d)
                   if n != "SHA256SUMS" and os.path.isfile(os.path.join(d, n)))
    lines = []
    for n in names:
        h = hashlib.sha256()
        with open(os.path.join(d, n), "rb") as f:
            for chunk in iter(lambda: f.read(1 << 20), b""):
                h.update(chunk)
        lines.append("%s  %s" % (h.hexdigest(), n))
    with open(os.path.join(d, "SHA256SUMS"), "w") as f:
        f.write("\n".join(lines) + "\n")


