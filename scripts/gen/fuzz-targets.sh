#!/usr/bin/env bash
# Generate (or --check) tests/coverage/fuzz-targets.toml from the actual
# fuzz-target source files under crates/*/fuzz/fuzz_targets/*.rs. The
# manifest is the single source of truth for the maintainer-local
# long-fuzz step before a release; --check fails CI when the manifest drifts from the
# tree (a target added/removed without regenerating).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="$ROOT/tests/coverage/fuzz-targets.toml"
tmp="$(mktemp)"
{
  echo "# GENERATED by scripts/gen/fuzz-targets.sh — do not hand-edit."
  echo "# Regenerate: scripts/gen/fuzz-targets.sh   |   CI check: scripts/gen/fuzz-targets.sh --check"
  echo "schema_version = 0"
  echo
  while IFS= read -r f; do
    crate="$(printf '%s\n' "$f" | sed -E 's|.*/crates/([^/]+)/fuzz/.*|\1|')"
    target="$(basename "$f" .rs)"
    printf '[[target]]\ncrate = "%s"\nname = "%s"\n\n' "$crate" "$target"
  done < <(find "$ROOT/crates" -path '*/fuzz/fuzz_targets/*.rs' | sort)
} > "$tmp"
if [ "${1:-}" = "--check" ]; then
  if ! diff -u "$OUT" "$tmp" >/dev/null 2>&1; then
    echo "fuzz-targets.toml is stale — run scripts/gen/fuzz-targets.sh" >&2
    diff -u "$OUT" "$tmp" || true
    rm -f "$tmp"; exit 1
  fi
  rm -f "$tmp"; echo "fuzz-targets.toml up to date"
else
  mkdir -p "$(dirname "$OUT")"; mv "$tmp" "$OUT"; echo "wrote $OUT"
fi
