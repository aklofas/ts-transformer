//! Maintainer tool: renders the binding kind tables from
//! `tst_pipeline::binding::{BindingErrorKind, Domain}`.
//!
//!   print-kinds                 the kind-equivalence TSV, to stdout
//!   print-kinds --write         rewrite scripts/ratchets/kind-equivalence.tsv and the
//!                               generated blocks in exceptions.py and the twelve
//!                               bindings/jvm/…/*Exception.java
//!   print-kinds --check         exit 1 (with a diff summary) if any committed copy
//!                               differs from a fresh render
//!   --root `<dir>`              the workspace root (default: the current directory)
//!
//! Not learner code. `scripts/check/repo/kind-equivalence.sh` runs `--check`.

use std::path::{Path, PathBuf};

use tst_pipeline::binding::{BindingErrorKind, Domain};

const TSV: &str = "scripts/ratchets/kind-equivalence.tsv";
const PY: &str = "bindings/python/python/tstrans/exceptions.py";
const JAVA_ROOT: &str = "bindings/jvm/src/main/java";
const PY_BEGIN: &str = "    # BEGIN GENERATED by print-kinds from crates/tst-pipeline/src/binding/kind.rs; do not edit";
const PY_END: &str = "    # END GENERATED by print-kinds";
const JAVA_BEGIN: &str = "        // BEGIN GENERATED by print-kinds from crates/tst-pipeline/src/binding/kind.rs; do not edit";
const JAVA_END: &str = "        // END GENERATED by print-kinds";

