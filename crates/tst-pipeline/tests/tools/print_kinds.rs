fn py_value(d: Domain, k: BindingErrorKind) -> Option<i64> {
    py_values(d)?
        .iter()
        .find(|(kk, _)| *kk == k)
        .map(|(_, v)| *v)
}

/// Exit 1 when a domain's kind list and its Python value table disagree.
fn validate() {
    let mut bad = false;
    for d in Domain::ALL {
        let Some(table) = py_values(*d) else { continue };
        for k in d.kinds() {
            if table.iter().filter(|(kk, _)| kk == k).count() != 1 {
                eprintln!(
                    "print-kinds: {d:?} kind {} has no (or a duplicate) Python value",
                    k.name()
                );
                bad = true;
            }
        }
        for (k, _) in table {
            if !d.kinds().contains(k) {
                eprintln!(
                    "print-kinds: {d:?} has a Python value for {}, which is not one of its kinds",
                    k.name()
                );
                bad = true;
            }
        }
    }
    if bad {
        std::process::exit(1);
    }
}

/// Widest doc line the generated comments carry, before their indent and
/// comment marker.
const WRAP: usize = 72;

/// The kind's doc text up to its first blank line (the Rust-source
/// paragraph that follows stays in the Rust docs), one entry per output
/// line: each source line is word-wrapped at [`WRAP`] columns.
fn doc_lines(k: &BindingErrorKind) -> Vec<String> {
    let mut out = Vec::new();
    for line in k.doc().lines() {
        let line = line.strip_prefix(' ').unwrap_or(line).trim_end();
        if line.is_empty() {
            break;
        }
        let mut cur = String::new();
        for word in line.split_whitespace() {
            if !cur.is_empty() && cur.len() + 1 + word.len() > WRAP {
                out.push(std::mem::take(&mut cur));
            }
            if !cur.is_empty() {
                cur.push(' ');
            }
            cur.push_str(word);
        }
        out.push(cur);
    }
    out
}

fn tsv() -> String {
    let mut out = String::from(
        "# GENERATED by print-kinds from crates/tst-pipeline/src/binding/kind.rs; do not edit.\n\
         # Regenerate: cargo run -p tst-pipeline --bin print-kinds -- --write\n\
         # rust_name\tmember\tc_code\tc_emit\tpy\tpy_parity\tjvm\tjvm_parity\n\
         #   one row per BindingErrorKind, in BindingErrorKind::ALL order; py / jvm list the\n\
         #   <Enum>.<member> each binding declares ('-' = none: a C-only kind, or a panic\n\
         #   that Python raises as PanicException and the JVM as RuntimeException).\n",
    );
    for k in BindingErrorKind::ALL {
        let py: Vec<String> = Domain::ALL
            .iter()
            .filter(|d| d.kinds().contains(k))
            .map(|d| format!("{}.{}", d.python_kind_enum(), k.name()))
            .collect();
        let jvm: Vec<String> = Domain::ALL
            .iter()
            .filter(|d| d.kinds().contains(k))
            .filter_map(|d| d.java_exception_class())
            .map(|c| format!("{}.Kind.{}", c.rsplit('/').next().unwrap_or(c), k.name()))
            .collect();
        let cell = |v: &[String]| {
            if v.is_empty() {
                "-".to_string()
            } else {
                v.join(";")
            }
        };
        out.push_str(&format!(
            "{}\t{}\t{}\t{}\t{}\tok\t{}\tok\n",
            k.variant_name(),
            k.name(),
            k.c_code(),
            k.c_projection(),
            cell(&py),
            cell(&jvm)
        ));
    }
    out
}

fn py_block(d: Domain) -> String {
    let mut out = String::new();
    for k in d.kinds() {
        for line in doc_lines(k) {
            out.push_str(&if line.is_empty() {
                "    #\n".to_string()
            } else {
                format!("    # {line}\n")
            });
        }
        let value = match py_value(d, *k) {
            Some(v) => v.to_string(),
            None => format!("\"{}\"", k.name().to_ascii_lowercase()),
        };
        out.push_str(&format!("    {} = {value}\n", k.name()));
    }
    out
}

fn java_block(d: Domain) -> String {
    let mut out = String::new();
    for k in d.kinds() {
        let lines = doc_lines(k);
        if lines.len() == 1 {
            out.push_str(&format!("        /** {} */\n", lines[0]));
        } else {
            out.push_str("        /**\n");
            for line in lines {
                out.push_str(&if line.is_empty() {
                    "         *\n".to_string()
                } else {
                    format!("         * {line}\n")
                });
            }
            out.push_str("         */\n");
        }
        out.push_str(&format!("        {},\n", k.name()));
    }
    out
}

/// Replace the text between the first `begin` marker line at or after
/// `anchor` and the next `end` marker line.
fn splice(text: &str, anchor: &str, begin: &str, end: &str, body: &str, file: &Path) -> String {
    let at = text
        .find(anchor)
        .unwrap_or_else(|| panic!("{}: no `{anchor}`", file.display()));
    let b = at
        + text[at..]
            .find(begin)
            .unwrap_or_else(|| panic!("{}: no BEGIN marker after `{anchor}`", file.display()));
    let body_start = b + begin.len() + 1;
    let e = body_start
        + text[body_start..]
            .find(end)
            .unwrap_or_else(|| panic!("{}: no END marker", file.display()));
    format!("{}{}{}", &text[..body_start], body, &text[e..])
}

fn rendered(root: &Path) -> Vec<(PathBuf, String)> {
    let mut files = vec![(root.join(TSV), tsv())];
    let py_path = root.join(PY);
    let mut py = std::fs::read_to_string(&py_path).expect("read exceptions.py");
    for d in Domain::ALL {
        py = splice(
            &py,
            &format!("class {}(", d.python_kind_enum()),
            PY_BEGIN,
            PY_END,
            &py_block(*d),
            &py_path,
        );
    }
    files.push((py_path, py));
    for d in Domain::ALL {
        if let Some(class) = d.java_exception_class() {
            let path = root.join(JAVA_ROOT).join(format!("{class}.java"));
            let java = std::fs::read_to_string(&path).expect("read exception class");
            files.push((
                path.clone(),
                splice(
                    &java,
                    "enum Kind",
                    JAVA_BEGIN,
                    JAVA_END,
                    &java_block(*d),
                    &path,
                ),
            ));
        }
    }
    files
}

fn main() {
    validate();
    let args: Vec<String> = std::env::args().skip(1).collect();
    let root = args
        .iter()
        .position(|a| a == "--root")
        .map(|i| PathBuf::from(&args[i + 1]))
        .unwrap_or_else(|| PathBuf::from("."));
    if args.iter().any(|a| a == "--write") {
        for (path, text) in rendered(&root) {
            std::fs::write(&path, text).expect("write generated file");
        }
    } else if args.iter().any(|a| a == "--check") {
        let mut stale = Vec::new();
        for (path, text) in rendered(&root) {
            if std::fs::read_to_string(&path).ok().as_deref() != Some(text.as_str()) {
                stale.push(path);
            }
        }
        if !stale.is_empty() {
            for p in &stale {
                eprintln!(
                    "kind-equivalence: {} differs from the kind table",
                    p.display()
                );
            }
            eprintln!("Regenerate: cargo run -p tst-pipeline --bin print-kinds -- --write");
            std::process::exit(1);
        }
        println!(
            "kind-equivalence: OK ({} kinds, {} domains)",
            BindingErrorKind::ALL.len(),
            Domain::ALL.len()
        );
    } else {
        print!("{}", tsv());
    }
}
