//! The pure half of `print-url-keys`: grouping the key-table rows into
//! documentation rows, rendering the Markdown table, and splicing it between
//! the generated-block markers.

use tst_core::url::query::KeyDoc;

pub const BEGIN: &str = "<!-- BEGIN GENERATED by print-url-keys; do not edit -->";
pub const END: &str = "<!-- END GENERATED by print-url-keys -->";

/// The order schemes are listed in, and the order their rows sort in.
pub const SCHEME_ORDER: [&str; 7] = ["udp", "rtp", "rtsp(s)", "tcp(s)", "hls(s)", "rist", "srt"];

/// One documentation row: a key, shared by every scheme that documents it
/// with the same aliases, meaning and unit.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Row {
    pub canonical: &'static str,
    pub aliases: &'static [&'static str],
    pub meaning: &'static str,
    pub unit: &'static str,
    pub schemes: Vec<&'static str>,
}

fn scheme_rank(s: &str) -> usize {
    SCHEME_ORDER
        .iter()
        .position(|x| *x == s)
        .unwrap_or(SCHEME_ORDER.len())
}

/// Merges rows with an equal (key, aliases, meaning, unit) and sorts by first
/// scheme, then key.
pub fn group(docs: impl IntoIterator<Item = KeyDoc>) -> Vec<Row> {
    let mut rows: Vec<Row> = Vec::new();
    for d in docs {
        match rows.iter_mut().find(|r| {
            r.canonical == d.canonical
                && r.aliases == d.aliases
                && r.meaning == d.meaning
                && r.unit == d.unit
        }) {
            Some(r) => {
                if !r.schemes.contains(&d.scheme) {
                    r.schemes.push(d.scheme);
                }
            }
            None => rows.push(Row {
                canonical: d.canonical,
                aliases: d.aliases,
                meaning: d.meaning,
                unit: d.unit,
                schemes: vec![d.scheme],
            }),
        }
    }
    for r in &mut rows {
        r.schemes.sort_by_key(|s| scheme_rank(s));
    }
    rows.sort_by(|a, b| {
        (scheme_rank(a.schemes[0]), a.canonical).cmp(&(scheme_rank(b.schemes[0]), b.canonical))
    });
    rows
}

/// A table cell: a `|` would end the cell, so it is escaped. Backticks are
/// left alone because the tables use them for code spans.
pub fn cell(text: &str) -> String {
    text.replace('|', "\\|")
}

fn key_cell(r: &Row) -> String {
    let mut s = format!("`{}`", r.canonical);
    if !r.aliases.is_empty() {
        let a: Vec<String> = r.aliases.iter().map(|a| format!("`{a}`")).collect();
        s.push_str(&format!(" (also {})", a.join(", ")));
    }
    s
}

/// The block text, markers included, ending in a newline.
pub fn render(rows: &[Row]) -> String {
    let mut out =
        format!("{BEGIN}\n\n| Key | Meaning | Unit or values | Schemes |\n|---|---|---|---|\n");
    for r in rows {
        let schemes: Vec<String> = r.schemes.iter().map(|s| format!("`{s}`")).collect();
        out.push_str(&format!(
            "| {} | {} | {} | {} |\n",
            cell(&key_cell(r)),
            cell(r.meaning),
            cell(r.unit),
            schemes.join(", ")
        ));
    }
    out.push_str(&format!("\n{END}\n"));
    out
}

/// `doc` with the text between the markers (markers included) replaced by
/// `block`; `None` when the markers are missing or out of order.
pub fn splice(doc: &str, block: &str) -> Option<String> {
    let b = doc.find(BEGIN)?;
    let e = doc.find(END)? + END.len();
    if e <= b {
        return None;
    }
    let tail = doc[e..].strip_prefix('\n').unwrap_or(&doc[e..]);
    Some(format!("{}{}{}", &doc[..b], block, tail))
}
