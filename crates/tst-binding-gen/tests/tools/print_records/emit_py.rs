//! The Python converter pair: `<snake>_to_py` and `<snake>_from_py` as
//! committed Rust text for `bindings/python/src/generated/<family>.rs`.

use crate::schema::{Entry, lookup, snake};
use crate::typemap::{Fld, Ty, resolve};

pub const HEADER: &str = "// GENERATED by print-records from tst-core binding_record! declarations; do not edit.\n\
// Regenerate: cargo run -p tst-binding-gen --bin print-records -- --write\n";

/// A one-line signature; rustfmt breaks it.
fn fn_sig(name: &str, params: &[String], ret: &str) -> String {
    format!("pub(crate) fn {name}({}) -> {ret} {{", params.join(", "))
}

fn conv_fn(reg: &[Entry], from: &Entry, name: &str, suffix: &str) -> String {
    let to = lookup(reg, name).expect("registered");
    let f = format!("{}_{suffix}", snake(name));
    if to.family == from.family {
        f
    } else {
        format!("crate::generated::{}::{f}", to.family)
    }
}

/// The value handed to `set_item` for a value of type `ty`. `place` is a
/// place expression; `by_ref` says it is a `&T` binding rather than a field.
fn py_val(
    reg: &[Entry],
    e: &Entry,
    ty: &Ty,
    place: &str,
    by_ref: bool,
    pre: &mut Vec<String>,
) -> String {
    let r = if by_ref {
        place.to_string()
    } else {
        format!("&{place}")
    };
    match ty {
        Ty::Scalar(_) => {
            if by_ref {
                format!("*{place}")
            } else {
                place.to_string()
            }
        }
        Ty::Str => format!("{place}.as_str()"),
        Ty::Bytes => format!("PyBytes::new_bound(py, {r})"),
        Ty::Record(n) => format!("{}(py, {r})?", conv_fn(reg, e, n, "to_py")),
        Ty::List(inner) => {
            let var = place.replace(['.', '*'], "_");
            let items = match inner.as_ref() {
                Ty::Record(n) => format!(
                    "let {var}_items = {place}.iter().map(|x| {}(py, x)).collect::<PyResult<Vec<_>>>()?;",
                    conv_fn(reg, e, n, "to_py")
                ),
                _ => format!("let {var}_items = {place}.iter().collect::<Vec<_>>();"),
            };
            pre.push(items);
            format!("PyTuple::new_bound(py, {var}_items)")
        }
        Ty::Opt(_) | Ty::Custom(_) | Ty::Map(_) | Ty::Host(_) => {
            unreachable!("refused or handled by the caller")
        }
    }
}

fn to_py(reg: &[Entry], e: &Entry, flds: &[Fld]) -> String {
    let s = &e.schema;
    let module = e.py_module;
    let mut o = fn_sig(
        &format!("{}_to_py", snake(s.name)),
        &["py: Python<'_>".into(), format!("r: &{}", e.rust_path)],
        "PyResult<PyObject>",
    );
    o.push('\n');
    o.push_str(&format!(
        "    let module = py.import_bound(\"{module}\")?;\n"
    ));
    o.push_str(&format!(
        "    let cls = module.getattr(intern!(py, \"{}\"))?;\n",
        e.name()
    ));
    o.push_str("    let kwargs = PyDict::new_bound(py);\n");
    for f in flds.iter().filter(|f| f.ty.is_some()) {
        let name = f.spec.name;
        let ty = f.ty.as_ref().expect("crossing");
        let key = format!("intern!(py, \"{name}\")");
        if f.custom {
            o.push_str(&format!(
                "    kwargs.set_item({key}, crate::custom::{}_{name}_to_py(py, &r.{name})?)?;\n",
                snake(s.name)
            ));
            continue;
        }
        let place = format!("r.{name}");
        if let Ty::Opt(inner) = ty {
            let mut pre = Vec::new();
            let v = py_val(reg, e, inner, "v", true, &mut pre);
            o.push_str(&format!("    if let Some(v) = &{place} {{\n"));
            for p in pre {
                o.push_str(&format!("        {p}\n"));
            }
            o.push_str(&format!("        kwargs.set_item({key}, {v})?;\n    }}\n"));
        } else {
            let mut pre = Vec::new();
            let v = py_val(reg, e, ty, &place, false, &mut pre);
            for p in pre {
                o.push_str(&format!("    {p}\n"));
            }
            o.push_str(&format!("    kwargs.set_item({key}, {v})?;\n"));
        }
    }
    o.push_str("    Ok(cls.call((), Some(&kwargs))?.unbind())\n}\n");
    o
}

/// An expression reading a host value `v` (a `Bound<PyAny>`) as `ty`.
fn py_read(reg: &[Entry], e: &Entry, ty: &Ty, v: &str) -> String {
    match ty {
        Ty::Opt(inner) => format!(
            "if {v}.is_none() {{ None }} else {{ Some({}) }}",
            py_read(reg, e, inner, v)
        ),
        Ty::Record(n) => format!("{}(&{v})?", conv_fn(reg, e, n, "from_py")),
        Ty::List(inner) if matches!(inner.as_ref(), Ty::Record(_)) => {
            let Ty::Record(n) = inner.as_ref() else {
                unreachable!()
            };
            format!(
                "{v}.iter()?.map(|x| x.and_then(|x| {}(&x))).collect::<PyResult<Vec<_>>>()?",
                conv_fn(reg, e, n, "from_py")
            )
        }
        _ => format!("{v}.extract()?"),
    }
}

fn from_py(reg: &[Entry], e: &Entry, flds: &[Fld]) -> String {
    let s = &e.schema;
    let path = e.rust_path;
    let mut o = fn_sig(
        &format!("{}_from_py", snake(s.name)),
        &["obj: &Bound<'_, PyAny>".into()],
        &format!("PyResult<{path}>"),
    );
    o.push('\n');
    o.push_str("    let py = obj.py();\n");
    let lines: Vec<(String, String)> = flds
        .iter()
        .map(|f| {
            let name = f.spec.name;
            let val = match &f.ty {
                None => "Default::default()".to_string(),
                Some(_) if f.custom => {
                    format!("crate::custom::{}_{name}_from_py(obj)?", snake(s.name))
                }
                Some(ty) => {
                    let get = format!("obj.getattr(intern!(py, \"{name}\"))?");
                    let simple = matches!(ty, Ty::Scalar(_) | Ty::Str | Ty::Bytes)
                        || matches!(ty, Ty::List(i) if !matches!(i.as_ref(), Ty::Record(_)));
                    if simple {
                        format!("{get}.extract()?")
                    } else {
                        format!("{{ let v = {get}; {} }}", py_read(reg, e, ty, "v"))
                    }
                }
            };
            (name.to_string(), val)
        })
        .collect();
    if s.non_exhaustive {
        o.push_str(&format!("    let mut r = {path}::default();\n"));
        for (n, v) in lines
            .iter()
            .filter(|(n, _)| flds.iter().any(|f| f.spec.name == n && f.ty.is_some()))
        {
            o.push_str(&format!("    r.{n} = {v};\n"));
        }
        o.push_str("    Ok(r)\n}\n");
    } else {
        o.push_str(&format!("    Ok({path} {{\n"));
        for (n, v) in &lines {
            o.push_str(&format!("        {n}: {v},\n"));
        }
        o.push_str("    })\n}\n");
    }
    o
}

/// The converter text for one record, per its direction.
pub fn record_pair(reg: &[Entry], e: &Entry) -> Result<String, String> {
    if e.is_native() {
        return crate::emit_pyclass::class(reg, e);
    }
    let flds = resolve(reg, &e.schema)?;
    if let Some(f) = flds
        .iter()
        .find(|f| !f.custom && f.ty.as_ref().is_some_and(Ty::is_to_host_only))
    {
        return Err(format!(
            "{}.{}: a map or a host-typed field is held by a native class only",
            e.schema.name, f.spec.name
        ));
    }
    let mut parts = Vec::new();
    if e.direction.crosses_out() {
        parts.push(to_py(reg, e, &flds));
    }
    if e.direction.crosses_in() {
        parts.push(from_py(reg, e, &flds));
    }
    Ok(parts.join("\n"))
}

/// The whole `generated/<family>.rs` text.
pub fn file(reg: &[Entry], family: &str) -> Result<String, String> {
    let mine: Vec<&Entry> = reg.iter().filter(|e| e.family == family).collect();
    if mine.iter().any(|e| e.is_native()) {
        return crate::emit_pyclass::file(reg, family);
    }
    let mut body = Vec::new();
    let mut uses_bytes = false;
    let mut uses_tuple = false;
    for e in &mine {
        for f in resolve(reg, &e.schema)?
            .iter()
            .filter_map(|f| f.ty.as_ref())
        {
            let mut t = f;
            while let Ty::Opt(i) | Ty::List(i) = t {
                if matches!(t, Ty::List(_)) {
                    uses_tuple = true;
                }
                t = i;
            }
            if matches!(t, Ty::Bytes) && e.direction.crosses_out() {
                uses_bytes = true;
            }
        }
        body.push(record_pair(reg, e)?);
    }
    let mut types = vec!["PyDict"];
    if uses_bytes {
        types.insert(0, "PyBytes");
    }
    if uses_tuple {
        types.push("PyTuple");
    }
    let crosses_out = mine.iter().any(|e| e.direction.crosses_out());
    let mut out = String::from(HEADER);
    out.push_str("\n#![allow(unsafe_op_in_unsafe_fn, clippy::useless_conversion)]\n\n");
    if crosses_out {
        out.push_str("use pyo3::intern;\n");
        out.push_str("use pyo3::prelude::*;\n");
        out.push_str(
            &format!("use pyo3::types::{{{}}};\n", types.join(", ")).replace("{PyDict}", "PyDict"),
        );
    } else {
        out.push_str("use pyo3::intern;\nuse pyo3::prelude::*;\n");
    }
    out.push('\n');
    out.push_str(&body.join("\n"));
    Ok(out)
}
