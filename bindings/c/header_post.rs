//! Build-script helpers shared by `build.rs` and `tests/abi/header_drift.rs`
//! through `#[path]`, so the drift test configures cbindgen exactly as the
//! build does. `tstrans.h` itself is cbindgen's output unchanged; what lives
//! here is the feature list, the `tstrans_config.h` text and the enum mirror
//! list. Plain std only: a build script cannot depend on the crate it builds.

/// The cargo features whose `#define TST_HAS_<NAME> 1` is written to the config, in order.
pub const FEATURES: &[&str] = &["SRT", "RTP", "UDP", "TCP", "HLS", "RIST", "TLS"];

/// The text of `tstrans_config.h` for a build with the `active` features: one
/// `#define TST_HAS_<F> 1` per active feature and nothing for the others.
/// `tstrans.h` includes this file; its trailer then defines every feature
/// macro left undefined to 0. An inactive feature must stay undefined here:
/// cbindgen guards each feature's declarations with `#if defined(TST_HAS_*)`,
/// so defining it to 0 would expose declarations the library does not have.
pub fn render_config(active: &[&str]) -> String {
    let mut out = String::from(
        "/* tstrans_config.h \u{2014} GENERATED by the tst-c build; do not edit.\n \
         * The cargo features this libtstrans was built with. tstrans.h includes\n \
         * this file; a feature that is absent here is not in the library. */\n\
         #ifndef TSTRANS_CONFIG_H\n\
         #define TSTRANS_CONFIG_H\n",
    );
    for f in active {
        out.push_str("#define TST_HAS_");
        out.push_str(f);
        out.push_str(" 1\n");
    }
    out.push_str("#endif /* TSTRANS_CONFIG_H */\n");
    out
}

/// Compares a freshly rendered header with the committed copy, ignoring line
/// endings (a Windows checkout turns the committed LF into CRLF). Returns
/// `None` when they match, else a message naming the first differing line.
pub fn header_differs(rendered: &str, committed: &str) -> Option<String> {
    let rendered = rendered.replace("\r\n", "\n");
    let committed = committed.replace("\r\n", "\n");
    if rendered == committed {
        return None;
    }
    let mut r = rendered.lines();
    let mut c = committed.lines();
    let mut n = 0;
    loop {
        n += 1;
        match (r.next(), c.next()) {
            (Some(a), Some(b)) if a == b => {}
            (a, b) => {
                return Some(format!(
                    "first difference at line {n}:\n  committed: {}\n  rendered:  {}",
                    b.unwrap_or("<end of file>"),
                    a.unwrap_or("<end of file>")
                ));
            }
        }
    }
}

/// Every `pub enum Tst*` declared at column 0 under `core_src`, sorted and
/// de-duplicated. cbindgen drops an enum no signature references unless it is
/// in `[export] include`; the build adds these so none can be forgotten.
pub fn mirror_enums(core_src: &std::path::Path) -> Vec<String> {
    fn walk(dir: &std::path::Path, out: &mut Vec<String>) {
        let mut entries: Vec<_> = std::fs::read_dir(dir)
            .unwrap_or_else(|e| panic!("read {}: {e}", dir.display()))
            .map(|e| {
                e.unwrap_or_else(|e| panic!("read {}: {e}", dir.display()))
                    .path()
            })
            .collect();
        entries.sort();
        for path in entries {
            if path.is_dir() {
                walk(&path, out);
            } else if path.extension().is_some_and(|x| x == "rs") {
                let text = std::fs::read_to_string(&path)
                    .unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
                for line in text.lines() {
                    if let Some(rest) = line.strip_prefix("pub enum Tst") {
                        let name: String = rest
                            .chars()
                            .take_while(|c| c.is_ascii_alphanumeric())
                            .collect();
                        if !name.is_empty() {
                            out.push(format!("Tst{name}"));
                        }
                    }
                }
            }
        }
    }
    let mut out = Vec::new();
    walk(core_src, &mut out);
    out.sort();
    out.dedup();
    out
}
