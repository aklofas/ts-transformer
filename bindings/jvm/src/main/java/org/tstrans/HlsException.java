package org.tstrans;

/**
 * Checked exception for the HLS publisher surface ({@code org.tstrans.hls}).
 * Mirrors tst-py's {@code tstrans.exceptions.HlsError} / {@code HlsErrorKind}.
 * {@link Kind} names are the Rust {@code BindingErrorKind} HLS variants with the
 * {@code HLS_} prefix stripped; the native library verifies at load time that
 * every kind it can raise resolves here (see {@code bindings/jvm/src/error.rs}).
 */
public final class HlsException extends BindingException {
    private static final long serialVersionUID = 1L;

    /**
     * HLS failure category. Persist {@link #name()}, never {@link #ordinal()}.
     */
    public enum Kind {
        // BEGIN GENERATED by print-kinds from crates/tst-pipeline/src/binding/kind.rs; do not edit
        /** `from_url` could not parse the HLS URL. */
        URL,
        /** Segment or playlist file I/O failed. */
        IO,
        /** The built-in HTTP server could not bind. */
        BIND_FAILED,
        /** The builder's configuration was rejected at `build()`. */
        INVALID_CONFIG,
        /** `push_ts` input is not a whole multiple of 188 bytes. */
        UNALIGNED_PUSH_TS,
        /** The publisher was already finished and takes no more data. */
        FINISHED,
        /** `enable_tls` was called on a build without the `tls` feature. */
        TLS_DISABLED,
        /** TLS setup failed (unreadable certificate or key, handshake). */
        TLS,
        /**
         * Library-internal failure: an invariant tripped that should not occur in
         * well-formed use (file an issue with reproduction bytes), a poisoned
         * handle lock, or an unmapped variant of a `#[non_exhaustive]` upstream
         * enum.
         */
        INTERNAL,
        /**
         * The handle or transport was closed: by `close()` on this object, by a
         * cancel or close from another thread while the call was parked (detail
         * "cancelled from another thread"), or the call came after the handle was
         * closed or consumed.
         */
        CLOSED,
        // END GENERATED by print-kinds
    }

    private final Kind kind;

    public HlsException(Kind kind, String message) {
        super(message);
        this.kind = kind;
    }

    /** @return the error discriminant. */
    public Kind kind() {
        return kind;
    }
}
