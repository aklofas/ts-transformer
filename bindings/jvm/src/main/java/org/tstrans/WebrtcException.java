package org.tstrans;

/**
 * Checked exception for the WebRTC (WHEP) playback surface ({@code org.tstrans.webrtc}).
 * Mirrors tst-py's {@code tstrans.exceptions.WebrtcError} / {@code WebrtcErrorKind}.
 * {@link Kind} names are the Rust {@code BindingErrorKind} WebRTC variants with the
 * {@code WEBRTC_} prefix stripped; the native library verifies at load time that
 * every kind it can raise resolves here (see {@code bindings/jvm/src/error.rs}).
 */
public final class WebrtcException extends BindingException {
    private static final long serialVersionUID = 1L;

    /**
     * WebRTC failure category. Persist {@link #name()}, never {@link #ordinal()}.
     */
    public enum Kind {
        // BEGIN GENERATED by print-kinds from crates/tst-pipeline/src/binding/kind.rs; do not edit
        /** The `whep://` / `wheps://` bind URL did not parse. */
        URL,
        /** The server's socket could not be bound. */
        IO,
        /** The certificate or key could not be loaded, or TLS setup failed. */
        TLS,
        /**
         * A mount call was refused: a duplicate or unknown path, an invalid
         * path, or an invalid mount configuration.
         */
        MOUNT,
        /** The WHEP server itself failed. */
        SERVER,
        /**
         * A push into a mount was refused: the wrong push family, an unusable
         * access unit or audio frame, or a KLV record over the data-channel
         * limit.
         */
        PUSH,
        /**
         * Library-internal failure: an invariant tripped that should not occur in
         * well-formed use (file an issue with reproduction bytes), or a poisoned
         * handle lock.
         */
        INTERNAL,
        /**
         * The handle or transport was closed: by `close()` on this object, by a
         * cancel or close from another thread while the call was parked (detail
         * "cancelled from another thread"), or the call came after the handle was
         * closed or consumed.
         */
        CLOSED,
        // END GENERATED by print-kinds
    }

    private final Kind kind;

    public WebrtcException(Kind kind, String message) {
        super(message);
        this.kind = kind;
    }

    /** @return the error discriminant. */
    public Kind kind() {
        return kind;
    }
}
