package org.tstrans;

import java.util.Optional;

/**
 * Thrown when typed-KLV encode fails. {@link Kind} mirrors
 * {@code tst_core::error::KlvEncodeError}; {@link #tag()} carries the
 * offending KLV tag for most tag-bearing variants, or the VTarget Pack
 * {@code target_id} for {@code V_TARGET_PACK_EMPTY} / {@code DUPLICATE_TARGET_ID}.
 */
public final class KlvEncodeException extends BindingException {
    private static final long serialVersionUID = 1L;

    /**
     * Discriminant; values map from the Rust {@code KlvEncodeError} variants.
     *
     * <p>Persist {@link #name()}, never {@link #ordinal()}: the declaration order is not part of the API
     * (0.7.0 moved {@code DUPLICATE_TARGET_ID} and {@code FORBIDDEN_STANDALONE_OFFSET} down one ordinal).
     */
    public enum Kind {
        // BEGIN GENERATED by print-kinds from crates/tst-pipeline/src/binding/kind.rs; do not edit
        /**
         * The output buffer cannot hold the encoded record.
         * `KlvEncodeError::BufferTooSmall`.
         */
        BUFFER_TOO_SMALL,
        /**
         * The encoded record exceeds the KLV size limit.
         * `KlvEncodeError::RecordTooLarge`.
         */
        RECORD_TOO_LARGE,
        /**
         * A value is outside the range the spec declares for its item.
         * `KlvEncodeError::OutOfRange`.
         */
        OUT_OF_RANGE,
        /**
         * A string value is longer than its item allows.
         * `KlvEncodeError::StringTooLong`.
         */
        STRING_TOO_LONG,
        /**
         * The IMAPB mapping length is outside the supported range 1 to 8 bytes.
         * `KlvEncodeError::UnsupportedImapbLength`.
         */
        UNSUPPORTED_IMAPB_LENGTH,
        /**
         * The IMAPB parameters violate the ST 1201.5 precondition that min is
         * below max.
         * `KlvEncodeError::InvalidImapbParams`.
         */
        INVALID_IMAPB_PARAMS,
        /**
         * A mandatory item is missing under a strict-compliance encoder.
         * `KlvEncodeError::MissingMandatoryItem`.
         */
        MISSING_MANDATORY_ITEM,
        /**
         * An unknown-tag entry used a tag the typed set reserves.
         * `KlvEncodeError::ReservedTagInUnknown`.
         */
        RESERVED_TAG_IN_UNKNOWN,
        /**
         * An ST 0903 VTarget Pack carried no items after its target id; the
         * error's tag is the target id.
         * `KlvEncodeError::VTargetPackEmpty`.
         */
        V_TARGET_PACK_EMPTY,
        /**
         * An ST 0903 vTargetSeries holds two VTarget Packs with the same target
         * id.
         * `KlvEncodeError::DuplicateTargetId`.
         */
        DUPLICATE_TARGET_ID,
        /**
         * A standalone ST 0903 VMTI set carries a parent-relative offset tag,
         * which the standalone form forbids.
         * `KlvEncodeError::ForbiddenStandaloneOffset`.
         */
        FORBIDDEN_STANDALONE_OFFSET,
        // END GENERATED by print-kinds
    }

    private final Kind kind;
    private final Long tag; // nullable — a KLV tag, or a VTarget target_id, depending on kind

    /** Construct with no associated tag (e.g. {@code BUFFER_TOO_SMALL}). */
    public KlvEncodeException(Kind kind, String message) {
        this(kind, null, message);
    }

    /** Construct with an associated KLV tag (e.g. {@code OUT_OF_RANGE}). */
    public KlvEncodeException(Kind kind, Long tag, String message) {
        super(message);
        this.kind = kind;
        this.tag = tag;
    }

    /** @return the error discriminant. */
    public Kind kind() {
        return kind;
    }

    /**
     * @return the numeric identifier the error carries, or empty for variants
     *     that carry none. For most variants this is the offending KLV tag; for
     *     {@code V_TARGET_PACK_EMPTY} / {@code DUPLICATE_TARGET_ID} it is the
     *     VTarget Pack {@code target_id}.
     */
    public Optional<Long> tag() {
        return Optional.ofNullable(tag);
    }
}
