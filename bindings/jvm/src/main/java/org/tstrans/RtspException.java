package org.tstrans;

/**
 * Checked exception for the RTSP control-plane surface ({@code org.tstrans.rtp}
 * RTSP client/server). Mirrors tst-py's {@code tstrans.exceptions.RtspError} /
 * {@code RtspErrorKind}. {@link Kind} collapses three Rust enums
 * ({@code tst_rtp::RtspError}, {@code RtspServerError}, {@code MountError}) onto
 * ten user-facing buckets — see {@code bindings/jvm/src/rtp/errors.rs}.
 */
public final class RtspException extends BindingException {
    private static final long serialVersionUID = 1L;

    /**
     * RTSP failure category. Names match tst-py {@code RtspErrorKind} 1:1.
     *
     * <p>Persist {@link #name()}, never {@link #ordinal()}: the declaration order is not part of the API.
     */
    public enum Kind {
        // BEGIN GENERATED by print-kinds from crates/tst-pipeline/src/binding/kind.rs; do not edit
        /** RTSP wire/protocol failure not covered by a finer RTSP kind. */
        PROTOCOL,
        /** RTSP credentials exhausted. */
        AUTH_FAILED,
        /** RTSP 401, or an unsupported auth scheme was demanded. */
        AUTH_REQUIRED,
        /** RTSP 404, or no uniquely-identified SDP media. */
        NOT_FOUND,
        /** RTSP 461 on every transport, or packetization-mode 2. */
        UNSUPPORTED_TRANSPORT,
        /** RTSP TLS failure (client or server). */
        TLS,
        /**
         * RTSP control-channel I/O failure (client, or server listener /
         * bind-in-use).
         */
        IO,
        /** RTSP request timeout. */
        TIMEOUT,
        /**
         * RTSP server lifecycle misuse: started twice, not started, or already
         * shut down.
         */
        SERVER,
        /**
         * RTSP mount failure: mount path, multicast group, duplicate mount or
         * mount config.
         */
        MOUNT,
        /**
         * The handle or transport was closed: by `close()` on this object, by a
         * cancel or close from another thread while the call was parked (detail
         * "cancelled from another thread"), or the call came after the handle was
         * closed or consumed.
         */
        CLOSED,
        // END GENERATED by print-kinds
    }

    private final Kind kind;

    public RtspException(Kind kind, String message) {
        super(message);
        this.kind = kind;
    }

    /** @return the error discriminant. */
    public Kind kind() {
        return kind;
    }
}
