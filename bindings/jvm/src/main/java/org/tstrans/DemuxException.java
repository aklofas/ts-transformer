package org.tstrans;

/**
 * Thrown when the MPEG-TS demuxer rejects input. Every {@link Kind} constant
 * maps 1:1 to a producing {@code tst_core::mpegts::demux::DemuxError} variant.
 * A failure converting a demux event inside the native library throws
 * {@code RuntimeException}, as Python raises {@code RuntimeError}.
 */
public final class DemuxException extends BindingException {
    private static final long serialVersionUID = 1L;

    /**
     * Discriminant; the names are the {@code BindingErrorKind} members,
     * verified against this enum at load time by {@link NativeLoader}.
     *
     * <p>Persist {@link #name()}, never {@link #ordinal()}: the declaration order is not part of the API
     * (0.7.0 reordered this enum: every ordinal names a different kind than it did in 0.6.x).
     */
    public enum Kind {
        // BEGIN GENERATED by print-kinds from crates/tst-pipeline/src/binding/kind.rs; do not edit
        /**
         * One sync-search window held no packet boundary; the scanned bytes are
         * discarded and the next feed starts a fresh search.
         */
        UNRECOVERABLE,
        /**
         * A strict-mode policy escalated a non-conformance to a fatal error; the
         * message names the specific issue.
         */
        STRICT_REJECTION,
        /**
         * A PES header declared a length too short to contain its own claimed
         * flags, so the reassembler cannot make forward progress.
         */
        MALFORMED_PES,
        /**
         * The pre-sync buffer filled without finding the four confirming sync
         * bytes; feed in smaller chunks or raise `sync_buf_cap`.
         */
        SYNC_BUF_EXHAUSTED,
        // END GENERATED by print-kinds
    }

    private final Kind kind;

    public DemuxException(Kind kind, String message) {
        super(message);
        this.kind = kind;
    }

    /** @return the error discriminant. */
    public Kind kind() {
        return kind;
    }
}
