package org.tstrans;

/**
 * Thrown when the MPEG-TS muxer rejects a config or push. {@link Kind} mirrors
 * the 5-variant {@code tst_core::error::MuxErrorKind} coarse classification
 * (the same buckets tst-py's {@code MuxErrorKind} uses).
 */
public final class MuxException extends BindingException {
    private static final long serialVersionUID = 1L;

    /**
     * Discriminant; values match the Rust {@code MuxErrorKind} variants.
     *
     * <p>Persist {@link #name()}, never {@link #ordinal()}: the declaration order is not part of the API.
     */
    public enum Kind {
        // BEGIN GENERATED by print-kinds from crates/tst-pipeline/src/binding/kind.rs; do not edit
        /**
         * The input is malformed for this call: framing was lost, or a payload was
         * over its size cap.
         */
        INPUT_MALFORMED,
        /**
         * Configuration rejected before anything was built: an invalid config,
         * URL, option or address.
         */
        CONFIG_INVALID,
        /**
         * API misuse on a successfully-built muxer: a stream handle from another
         * muxer, an ambiguous-target shorthand on a multi-stream muxer, an unknown
         * program reference, or an out-of-range descriptor or index.
         */
        INVALID_USAGE,
        /**
         * Transient refusal: the transport or muxer is alive but cannot take or
         * produce the call now (full send queue or muxer buffer, or a receive
         * deadline that expired). Retry; the handle stays open.
         */
        BACKPRESSURE,
        /**
         * Library-internal failure: an invariant tripped that should not occur in
         * well-formed use (file an issue with reproduction bytes), or a poisoned
         * handle lock.
         */
        INTERNAL,
        /**
         * A pushed video access unit carried no Annex-B start code, so it is not a
         * NAL.
         */
        INVALID_NAL,
        /** A KLV record exceeded the PES length cap. */
        KLV_TOO_LARGE,
        /**
         * The AV1 OBU stream could not be framed: it is not a well-formed OBU
         * stream.
         */
        INVALID_AV1_OBU,
        /**
         * The MISP ST 0604 timestamp SEI could not be built or inserted for this
         * codec or carriage (the `push_video_misp_to` family).
         */
        MISP_TIME,
        // END GENERATED by print-kinds
    }

    private final Kind kind;

    public MuxException(Kind kind, String message) {
        super(message);
        this.kind = kind;
    }

    /** @return the error discriminant. */
    public Kind kind() {
        return kind;
    }
}
