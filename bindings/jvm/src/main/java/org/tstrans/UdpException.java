package org.tstrans;

/**
 * Checked exception thrown by an {@code org.tstrans.shells} class opened from a
 * {@code udp://} URL (plain UDP datagrams).
 * Mirrors tst-py's {@code tstrans.exceptions.UdpError} / {@code UdpErrorKind}.
 * {@link Kind} names are the Rust {@code BindingErrorKind} variants of the UDP domain with the
 * {@code UDP_} prefix stripped where there is one; the native library
 * verifies at load time that every kind it can
 * raise resolves here (see {@code bindings/jvm/src/error.rs}).
 */
public final class UdpException extends BindingException {
    private static final long serialVersionUID = 1L;

    /**
     * UDP failure category. Persist {@link #name()}, never {@link #ordinal()}.
     */
    public enum Kind {
        // BEGIN GENERATED by print-kinds from crates/tst-pipeline/src/binding/kind.rs; do not edit
        /** The `udp://` URL could not be parsed. */
        URL,
        /** UDP socket I/O failure (bind, connect or socket option). */
        IO,
        /** The payload exceeds the transport's per-send ceiling. */
        TOO_LARGE,
        /**
         * The handle or transport was closed: by `close()` on this object, by a
         * cancel or close from another thread while the call was parked (detail
         * "cancelled from another thread"), or the call came after the handle was
         * closed or consumed.
         */
        CLOSED,
        /** The UDP configuration was rejected. */
        INVALID_CONFIG,
        /**
         * Transient refusal: the transport or muxer is alive but cannot take or
         * produce the call now (full send queue or muxer buffer, or a receive
         * deadline that expired). Retry; the handle stays open.
         */
        BACKPRESSURE,
        /**
         * The transport is dead (a send or receive I/O failure, never a cancel);
         * reopen it.
         */
        BROKEN,
        /**
         * The input is malformed for this call: framing was lost, or a payload was
         * over its size cap.
         */
        INPUT_MALFORMED,
        /**
         * The receive loop reached end of stream: the peer closed cleanly. The
         * receiver is dead; later calls report `CLOSED`. Iterating receivers end
         * the iteration instead of raising it.
         */
        END_OF_STREAM,
        /**
         * Configuration rejected before anything was built: an invalid config,
         * URL, option or address.
         */
        CONFIG_INVALID,
        // END GENERATED by print-kinds
    }

    private final Kind kind;

    public UdpException(Kind kind, String message) {
        super(message);
        this.kind = kind;
    }

    /** @return the error discriminant. */
    public Kind kind() {
        return kind;
    }
}
