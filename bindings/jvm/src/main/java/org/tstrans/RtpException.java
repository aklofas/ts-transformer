package org.tstrans;

/**
 * Checked exception for the RTP transport surface ({@code org.tstrans.rtp}).
 * {@link Kind} carries the Rust {@code tst_core::transport::TransportError}
 * projections an rtp shell can raise plus {@code tst_rtp::ConnectError}'s six
 * variants; the names are the {@code BindingErrorKind} members, verified
 * against this enum at load time by {@link NativeLoader}.
 */
public final class RtpException extends BindingException {
    private static final long serialVersionUID = 1L;

    /**
     * Failure category.
     *
     * <p>Persist {@link #name()}, never {@link #ordinal()}: the declaration order is not part of the API.
     */
    public enum Kind {
        // BEGIN GENERATED by print-kinds from crates/tst-pipeline/src/binding/kind.rs; do not edit
        /**
         * The transport is dead (a send or receive I/O failure, never a cancel);
         * reopen it.
         * `TransportError::Broken`, SRT `ConnectionBroken`.
         */
        BROKEN,
        /**
         * The payload exceeds the transport's per-send ceiling.
         * `TransportError::TooLarge`, SRT `PayloadTooLarge` / `BufferTooSmall`.
         */
        TOO_LARGE,
        /**
         * The handle or transport was closed: by `close()` on this object, by a
         * cancel or close from another thread while the call was parked (detail
         * "cancelled from another thread"), or the call came after the handle was
         * closed or consumed.
         * `TransportError::{Closed on a sender, ExplicitClose}`,
         * `HandleState::Closed`, `TcpError::Closed`, SRT `ListenerClosed` /
         * `SocketClosed`.
         */
        CLOSED,
        /**
         * Transient refusal: the transport or muxer is alive but cannot take or
         * produce the call now (full send queue or muxer buffer, or a receive
         * deadline that expired). Retry; the handle stays open.
         * `TransportError::Backpressure`, `MuxError::BufferFull`, SRT `QueueFull`.
         */
        BACKPRESSURE,
        /**
         * The URL carries `?pt=` (elementary RTP): use the H.264 receiver, not the
         * MP2T transport.
         * tst-rtp `ConnectError::PayloadTypeParam`.
         */
        PAYLOAD_TYPE_PARAM,
        /**
         * The H.264 receiver requires a dynamic payload type in `?pt=` on the URL.
         * tst-rtp `ConnectError::MissingPayloadTypeParam`.
         */
        MISSING_PAYLOAD_TYPE_PARAM,
        /**
         * The `rtp://` or `rtsp://` URL could not be parsed.
         * tst-rtp `ConnectError::Url`.
         */
        URL,
        /**
         * The host is not a literal IPv4 or IPv6 address. The RTP transport does
         * no DNS resolution: pre-resolve it and pass the literal.
         * tst-rtp `ConnectError::HostNotLiteral`.
         */
        HOST_NOT_LITERAL,
        /**
         * UDP socket error: an OS-level bind, connect or setsockopt failure.
         * tst-rtp `ConnectError::Io`.
         */
        IO,
        /**
         * The multicast interface is unsupported here, typically because the
         * platform needs a different form (IPv6 needs a scope-id integer).
         * tst-rtp `ConnectError::IfaceUnsupported`.
         */
        IFACE_UNSUPPORTED,
        /**
         * The receive loop reached end of stream: the peer closed cleanly. The
         * receiver is dead; later calls report `CLOSED`. Iterating receivers end
         * the iteration instead of raising it.
         * `ShellErrorKind::EndOfStream`; the C ABI returns it as
         * `TST_E_END_OF_STREAM` (-12).
         */
        END_OF_STREAM,
        // END GENERATED by print-kinds
    }

    private final Kind kind;

    public RtpException(Kind kind, String message) {
        super(message);
        this.kind = kind;
    }

    /** @return the error discriminant. */
    public Kind kind() {
        return kind;
    }
}
