package org.tstrans;

/**
 * Checked exception for the SRT transport surface ({@code org.tstrans.srt}).
 * Mirrors tst-py's {@code tstrans.exceptions.SrtError} / {@code SrtErrorKind}.
 * {@link Kind} maps the Rust {@code tst_srt} error families
 * (UrlError / ConnectError / BindError / AcceptError / IoError / TransportError)
 * onto eleven user-facing buckets — see {@code bindings/jvm/src/srt/errors.rs}.
 *
 * <h2>{@code END_OF_STREAM}</h2>
 *
 * <p>Two producers:
 * <ul>
 *   <li>a peer closes the session cleanly — a sender opened with the
 *       sender preset ({@code SRTO_SENDER} + linger), e.g. via the C
 *       ABI or an {@code org.tstrans.srt.ManagedSender}; the plain JVM
 *       caller shells do not set that preset, so a JVM-to-JVM plain
 *       loopback reports {@code BROKEN} instead;</li>
 *   <li>an {@code org.tstrans.srt.ManagedReceiver} whose reconnect
 *       budget is exhausted — the decorator gives up and the receive
 *       direction classifies that as end of stream.</li>
 * </ul>
 *
 * <p>The message carries the transport's own text, which differs
 * between the two.
 */
public final class SrtException extends BindingException {
    private static final long serialVersionUID = 1L;

    /**
     * SRT failure category. Names are the Rust {@code BindingErrorKind} variant
     * names in SCREAMING_SNAKE_CASE (the kind rule, 0.7.0); the native library
     * verifies at load time that every kind it can raise resolves here.
     *
     * <p>Persist {@link #name()}, never {@link #ordinal()}: the declaration order is not part of the API
     * (0.7.0 removed {@code WOULD_BLOCK}, which moved {@code IO} from ordinal 7 to 6).
     */
    public enum Kind {
        // BEGIN GENERATED by print-kinds from crates/tst-pipeline/src/binding/kind.rs; do not edit
        /**
         * SRT connect / bind failed (refused, rejected, bad encryption, address in
         * use, permission, system).
         */
        CONNECT_FAILED,
        /** SRT accept failed (peer rejected during handshake, system). */
        ACCEPT_FAILED,
        /**
         * Transient refusal: the transport or muxer is alive but cannot take or
         * produce the call now (full send queue or muxer buffer, or a receive
         * deadline that expired). Retry; the handle stays open.
         */
        BACKPRESSURE,
        /** SRT connect / accept / send / recv timed out. */
        TIMEOUT,
        /**
         * The handle or transport was closed: by `close()` on this object, by a
         * cancel or close from another thread while the call was parked (detail
         * "cancelled from another thread"), or the call came after the handle was
         * closed or consumed.
         */
        CLOSED,
        /**
         * The transport is dead (a send or receive I/O failure, never a cancel);
         * reopen it.
         */
        BROKEN,
        /**
         * Configuration rejected before anything was built: an invalid config,
         * URL, option or address.
         */
        CONFIG_INVALID,
        /**
         * SRT low-level I/O failure (`IoError`, `SendError` / `RecvError` system
         * or libsrt errors).
         */
        IO,
        /** The payload exceeds the transport's per-send ceiling. */
        TOO_LARGE,
        /**
         * The input is malformed for this call: framing was lost, or a payload was
         * over its size cap.
         */
        INPUT_MALFORMED,
        /**
         * The receive loop reached end of stream: the peer closed cleanly. The
         * receiver is dead; later calls report `CLOSED`. Iterating receivers end
         * the iteration instead of raising it.
         */
        END_OF_STREAM,
        // END GENERATED by print-kinds
    }

    private final Kind kind;

    public SrtException(Kind kind, String message) {
        super(message);
        this.kind = kind;
    }

    /** @return the error discriminant. */
    public Kind kind() {
        return kind;
    }
}
